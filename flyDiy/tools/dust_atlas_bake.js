#!/usr/bin/env node
// dust_atlas_bake.js - DIRT-DUST V2 (11 Nov): bakes the dust puff's six-way atlas ONCE, here, so the game never bakes it
// at load (dust.js sixWay: ~1 s on the box, more on a phone). Writes:
//   media/tex/dust/dustsix_a.<sha8>.png   +x, +y, -z (from behind) lit, coverage in alpha
//   media/tex/dust/dustsix_b.<sha8>.png   -x, -y, +z (the eye's side) lit
//   src/viewer/dust_atlas.js              GENERATED: the two paths, the frame layout, tauRef, the per-frame gain, a sig
// PNG rows run top-down, so the atlas's row H-1 is written first: a browser image with THREE's flipY (the default)
// lands row 0 at v = 0, as the DataTexture fallback does.
//
//   node tools/dust_atlas_bake.js          (re-run after any change to dust.js sixWay; GATE DUST fails on a stale atlas)
'use strict';
const fs = require('fs'), path = require('path'), zlib = require('zlib'), crypto = require('crypto');
const DUST = require('../src/viewer/dust.js');
const { writeMedia, pruneMedia } = require('./_media_lib.js');
const ROOT = path.join(__dirname, '..');

function png(W, H, rgba) {
  const raw = Buffer.alloc((W * 4 + 1) * H);
  for (let y = 0; y < H; y++) {
    const src = (H - 1 - y) * W * 4, dst = y * (W * 4 + 1);
    raw[dst] = 0;   // filter: none
    Buffer.from(rgba.buffer, rgba.byteOffset + src, W * 4).copy(raw, dst + 1);
  }
  const chunk = (type, data) => {
    const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
    const td = Buffer.concat([Buffer.from(type, 'ascii'), data]);
    const crc = Buffer.alloc(4); crc.writeUInt32BE(zlib.crc32(td) >>> 0);
    return Buffer.concat([len, td, crc]);
  };
  const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(W, 0); ihdr.writeUInt32BE(H, 4); ihdr[8] = 8; ihdr[9] = 6; ihdr[10] = 0; ihdr[11] = 0; ihdr[12] = 0;
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(raw, { level: 9 })), chunk('IEND', Buffer.alloc(0))]);
}
// the atlas's signature: what GATE DUST compares a fresh bake against
const sigOf = S => crypto.createHash('sha256').update(Buffer.from(S.A.buffer)).update(Buffer.from(S.B.buffer)).digest('hex').slice(0, 16);

if (require.main === module) {
  const t0 = Date.now(), S = DUST.sixWay();
  const pa = writeMedia('tex/dust', 'dustsix_a', 'png', png(S.W, S.H, S.A)), pb = writeMedia('tex/dust', 'dustsix_b', 'png', png(S.W, S.H, S.B));
  pruneMedia('tex/dust', [pa, pb]);   // the baker owns media/tex/dust: an older atlas goes (GATE MEDIA's orphans)
  const r = v => Math.round(v * 1e4) / 1e4;
  const meta = { A: pa, B: pb, W: S.W, H: S.H, F: S.F, C: S.C, R: S.R, PX: S.PX, tauRef: r(S.tauRef), zoom: S.zoom, gain: S.gain.map(r), sig: sigOf(S) };
  const out = '// dust_atlas.js - GENERATED by tools/dust_atlas_bake.js (DIRT-DUST V2, 11 Nov): the dust puff\'s six-way atlas, baked\n' +
    '// once (dust.js sixWay) and shipped as two images, so the page never bakes it at load. Do not edit: re-run the baker.\n' +
    "'use strict';\nvar DUST_ATLAS = " + JSON.stringify(meta) + ';\n' +
    "if (typeof window !== 'undefined') window.DUST_ATLAS = DUST_ATLAS;\nif (typeof module !== 'undefined' && module.exports) module.exports = DUST_ATLAS;\n";
  fs.writeFileSync(path.join(ROOT, 'src', 'viewer', 'dust_atlas.js'), out);
  console.log('dust_atlas_bake: ' + pa + ' + ' + pb + ' (' + fs.statSync(path.join(ROOT, pa)).size + ' + ' + fs.statSync(path.join(ROOT, pb)).size + ' bytes), sig ' + meta.sig + ', ' + (Date.now() - t0) + ' ms');
}
module.exports = { png, sigOf };
