# G3615 (PEOPLE-FACES): the people's portraits, cut for the game from the user's originals (assets/chars/people, untracked,
# never written). A0's rules (25 Oct, after the user's "unacceptable" red specks round the hair - the originals hold
# background-removal leftovers, pure red at alpha 1-23, black at alpha 0):
#  (1) never drop alpha - a preview is alpha_composite over a background colour
#  (2) every resize is premultiplied (PIL 'RGBa')
#  (3) shipped copies get a clean-edge pass: RGB of alpha<32 pixels from the nearest opaque pixel (originals untouched)
#  (4) check: no r>200,g<40,b<40 pixel at 8<=alpha<240 (the rim) - opaque red is clothing (Pete vest, Stig suit)
#   python -I portrait_prep.py preview <src.png> <out.png> <px> [#rrggbb]
#   python -I portrait_prep.py ship <src.png> <out.webp> <px>
#   python -I portrait_prep.py check <file>...
#   python -I portrait_prep.py all [<originals dir>]   every person of src/core/72_people.js at PEOPLE_FACE_PX, written
#        as media/people/<id>_<px>.<sha8>.webp (content-named: sw.js serves media/ cache-first) + src/core/72_people_faces.js
#        (the map peopleFace reads); stale cuts removed; every written file checked. Default originals: the main
#        checkout's flyDiy/assets/chars/people.
#   python -I portrait_prep.py bgs [<originals dir>]   G3620: every scene of 72_people.js PEOPLE_BG_SCENES, cut to
#        PEOPLE_BG_PX (opaque, a plain LANCZOS square) as media/people/<the user's name>_<px>.<sha8>.webp + src/core/72_people_bgs.js
#        (peopleBg reads it); stale bg cuts removed. Default originals: the user's inbox backgrounds-2026-10-26 (BG-<type>.png).
import hashlib, io, os, re, sys
import numpy as np
from PIL import Image

def _pushpull(rgb, m):
    # fill rgb where ~m from the nearest solid pixels (pyramid push-pull; no scipy on the box)
    h, w = m.shape
    if m.all() or not m.any() or (h <= 1 and w <= 1): return rgb
    H, W = h + (h & 1), w + (w & 1)
    r = np.zeros((H, W, 3)); k = np.zeros((H, W))
    r[:h, :w] = rgb * m[..., None]; k[:h, :w] = m
    rs = r.reshape(H // 2, 2, W // 2, 2, 3).sum((1, 3)); ks = k.reshape(H // 2, 2, W // 2, 2).sum((1, 3))
    cm = ks > 0
    c = np.where(cm[..., None], rs / np.maximum(ks, 1)[..., None], 0)
    c = _pushpull(c, cm)
    up = c.repeat(2, 0).repeat(2, 1)[:h, :w]
    out = rgb.copy(); out[~m] = up[~m]
    return out

def clean_edge(im):
    a = np.asarray(im.convert('RGBA')).copy()
    solid = a[..., 3] >= 32
    a[..., :3] = np.clip(np.rint(_pushpull(a[..., :3].astype(float), solid)), 0, 255).astype(np.uint8)
    return Image.fromarray(a, 'RGBA')

def resize(im, px):
    w, h = im.size
    s = px / max(w, h)
    return im.convert('RGBa').resize((max(1, round(w * s)), max(1, round(h * s))), Image.LANCZOS).convert('RGBA')

def reds(im):
    a = np.asarray(im.convert('RGBA')).astype(int)
    return int(((a[..., 0] > 200) & (a[..., 1] < 40) & (a[..., 2] < 40) & (a[..., 3] >= 8) & (a[..., 3] < 240)).sum())

BG_FILE = re.compile(r'^BG-[\w-]+_\d+\.[0-9a-f]{8}\.webp$')   # a background's cut: <the user's BG-<type>>_<px>.<sha8>.webp
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

def ship_all(orig):
    src = io.open(os.path.join(ROOT, 'src', 'core', '72_people.js'), encoding='utf-8').read()
    rows = re.findall(r"^  (\w+):\s*\{ id: '(\w+)',\s*name: '[^']*',\s*file: '([^']+)'", src, re.M)
    pxs = [int(x) for x in re.search(r"const PEOPLE_FACE_PX = \[([\d, ]+)\]", src).group(1).split(',')]
    if not orig:
        orig = os.path.join(ROOT, 'assets', 'chars', 'people')
        if not os.path.isdir(orig): orig = 'D:/Dev/DeGaRoR.github.io/flyDiy/assets/chars/people'
    out_dir = os.path.join(ROOT, 'media', 'people'); os.makedirs(out_dir, exist_ok=True)
    faces, keep, total, bad = {}, set(), 0, 0
    for key, pid, f in rows:
        assert key == pid, key
        im0 = clean_edge(Image.open(os.path.join(orig, f + '.png')))
        for px in pxs:
            im = clean_edge(resize(im0, px))
            b = io.BytesIO(); im.save(b, 'WEBP', quality=88, method=6, exact=False); data = b.getvalue()
            n = reds(Image.open(io.BytesIO(data)))
            if n: print('FAIL ' + pid + ' ' + str(px) + ': ' + str(n) + ' red rim pixel(s)'); bad += 1; continue
            name = pid + '_' + str(px) + '.' + hashlib.sha256(data).hexdigest()[:8] + '.webp'
            io.open(os.path.join(out_dir, name), 'wb').write(data)
            faces[pid + '_' + str(px)] = name; keep.add(name); total += len(data)
    for f in os.listdir(out_dir):
        if f.endswith('.webp') and not BG_FILE.match(f) and f not in keep: os.remove(os.path.join(out_dir, f))
    js = ['// GENERATED by tools/portrait_prep.py all (G3615) - the portraits of the people as cut, content-named: do not edit.',
          '// <id>_<px> -> the file under media/people/ (72_people.js peopleFace reads it).',
          'const PEOPLE_FACES = {']
    js += ["  '" + k + "': '" + faces[k] + "'," for k in sorted(faces)]
    js += ['};', '']
    io.open(os.path.join(ROOT, 'src', 'core', '72_people_faces.js'), 'w', encoding='utf-8', newline='\n').write('\n'.join(js))
    print(str(len(faces)) + ' cuts of ' + str(len(rows)) + ' people at ' + str(pxs) + ', ' + str(round(total / 1024)) + ' KiB, ' + str(bad) + ' refused')
    return 1 if bad else 0

def ship_bgs(orig):
    src = io.open(os.path.join(ROOT, 'src', 'core', '72_people.js'), encoding='utf-8').read()
    block = re.search(r"const PEOPLE_BG_SCENES = \{(.*?)\n\};", src, re.S).group(1)
    scenes = re.findall(r"^  '([^']+)':", block, re.M)   # the user's own file names, kept as they are
    px = int(re.search(r"const PEOPLE_BG_PX = (\d+);", src).group(1))
    orig = orig or 'D:/Dev/flydiy-notes/inbox/backgrounds-2026-10-26'   # the user's BG-<type>.png
    out_dir = os.path.join(ROOT, 'media', 'people'); os.makedirs(out_dir, exist_ok=True)
    bgs, keep, total = {}, set(), 0
    for sc in scenes:
        im = Image.open(os.path.join(orig, sc + '.png')).convert('RGB')
        w, h = im.size; e = min(w, h)
        im = im.crop(((w - e) // 2, (h - e) // 2, (w - e) // 2 + e, (h - e) // 2 + e)).resize((px, px), Image.LANCZOS)
        b = io.BytesIO(); im.save(b, 'WEBP', quality=80, method=6); data = b.getvalue()
        name = sc + '_' + str(px) + '.' + hashlib.sha256(data).hexdigest()[:8] + '.webp'
        io.open(os.path.join(out_dir, name), 'wb').write(data)
        bgs[sc + '_' + str(px)] = name; keep.add(name); total += len(data)
    for f in os.listdir(out_dir):
        if BG_FILE.match(f) and f not in keep: os.remove(os.path.join(out_dir, f))
    js = ['// GENERATED by tools/portrait_prep.py bgs (G3620) - the portrait backgrounds as cut, content-named: do not edit.',
          '// <the user file name>_<px> -> the file under media/people/ (72_people.js peopleBg reads it).',
          'const PEOPLE_BGS = {']
    js += ["  '" + k + "': '" + bgs[k] + "'," for k in sorted(bgs)]
    js += ['};', '']
    io.open(os.path.join(ROOT, 'src', 'core', '72_people_bgs.js'), 'w', encoding='utf-8', newline='\n').write('\n'.join(js))
    print(str(len(bgs)) + ' backgrounds at ' + str(px) + ' px, ' + str(round(total / 1024)) + ' KiB')
    return 0 if len(bgs) == len(scenes) else 1

def main(argv):
    cmd = argv[0]
    if cmd == 'preview':
        src, out, px = argv[1], argv[2], int(argv[3])
        bg = argv[4] if len(argv) > 4 else '#2b2e34'
        im = resize(clean_edge(Image.open(src)), px)
        ground = Image.new('RGBA', im.size, bg)
        Image.alpha_composite(ground, im).convert('RGB').save(out)
    elif cmd == 'ship':
        src, out, px = argv[1], argv[2], int(argv[3])
        im = clean_edge(resize(clean_edge(Image.open(src)), px))
        n = reds(im)
        if n: print('FAIL ' + out + ': ' + str(n) + ' red pixel(s) at alpha>=8'); return 1
        im.save(out, 'WEBP', quality=88, method=6, exact=False)
    elif cmd == 'all':
        return ship_all(argv[1] if len(argv) > 1 else None)
    elif cmd == 'bgs':
        return ship_bgs(argv[1] if len(argv) > 1 else None)
    elif cmd == 'check':
        bad = 0
        for f in argv[1:]:
            n = reds(Image.open(f)); print(('FAIL ' if n else 'ok   ') + f + ' ' + str(n)); bad += n > 0
        return 1 if bad else 0
    return 0

if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
