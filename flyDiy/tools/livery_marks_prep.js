#!/usr/bin/env node
// livery_marks_prep.js - THE LIVERY STICKERS' GAME COPY (LIVERY-STICKERS, 9 Nov 2026)
//   node tools/livery_marks_prep.js [--check]
// assets-src/stickers/cut.json (flatten.py's cutter-ready paths) -> src/viewer/livery_marks.js, window.LIVERY_MARKS:
// the twelve marks as closed rings, in the mark's own units (its viewBox), each point a tenth of a unit, the first
// point absolute and the rest as deltas ("x,y dx,dy ..."). Each ring is thinned by Douglas-Peucker at 0.08 units (a
// 240-unit mark in a 1024 px atlas cell is 0.3 px; the cutter's own copy, svg/, keeps 0.03). Filled even-odd: the parts
// never overlap, so a hole is a ring inside a ring.
// It is a LAZY file (build.js MANIFEST.lazy): aeroskin.js keeps only the marks' names and sizes inline
// (AERO_VINYL_MARKS) and asks for the geometry the first time a sticker is drawn. --check: exit 1 if the committed
// file is not what this would write (GATE LIVERYSTICKERS runs it).
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'assets-src', 'stickers');
const OUT = path.join(ROOT, 'src', 'viewer', 'livery_marks.js');
const TOL = 0.08, Q = 10;

function rdp(P, tol) {                     // Douglas-Peucker on an open polyline (keeps both ends)
  if (P.length < 3) return P.slice();
  const keep = new Uint8Array(P.length); keep[0] = keep[P.length - 1] = 1;
  const st = [[0, P.length - 1]];
  while (st.length) {
    const [a, b] = st.pop(); let md = -1, mi = -1;
    const [ax, ay] = P[a], [bx, by] = P[b], dx = bx - ax, dy = by - ay, L = Math.hypot(dx, dy) || 1e-12;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs((P[i][0] - ax) * dy - (P[i][1] - ay) * dx) / L;
      if (d > md) { md = d; mi = i; }
    }
    if (md > tol) { keep[mi] = 1; st.push([a, mi], [mi, b]); }
  }
  return P.filter((_, i) => keep[i]);
}
function ringThin(P) {                     // a closed ring: split at the point farthest from the first, thin both halves
  let far = 0, fd = -1;
  for (let i = 1; i < P.length; i++) { const d = Math.hypot(P[i][0] - P[0][0], P[i][1] - P[0][1]); if (d > fd) { fd = d; far = i; } }
  const a = rdp(P.slice(0, far + 1), TOL), b = rdp(P.slice(far).concat([P[0]]), TOL);
  return a.concat(b.slice(1, -1));
}
function build() {
  const cut = JSON.parse(fs.readFileSync(path.join(SRC, 'cut.json'), 'utf8'));
  const marks = cut.map(m => {
    const svg = fs.readFileSync(path.join(SRC, 'svg', m.file), 'utf8');
    const t = (svg.match(/<title>flyDiy sticker \d+: (.*?)<\/title>/) || [])[1] || m.file;
    const rings = (m.d.match(/M[^Z]*Z/g) || []).map(r => r.slice(1, -1).split(/[ L]+/).filter(Boolean)
      .map(p => p.split(',').map(Number)));
    const enc = rings.map(ringThin).filter(r => r.length >= 3).map(r => {
      const q = r.map(([x, y]) => [Math.round(x * Q), Math.round(y * Q)]);
      return q.map((p, i) => i ? (p[0] - q[i - 1][0]) + ',' + (p[1] - q[i - 1][1]) : p[0] + ',' + p[1]).join(' ');
    });
    // THE INK'S OWN BOX (b: x0, y0, x1, y1, in units, from the encoded points): a sticker's size is its ink's height, and
    // the cell is fitted to the ink, not to the drawing's margin
    const b = [1e9, 1e9, -1e9, -1e9];
    for (const r of enc) { let x = 0, y = 0; r.split(' ').forEach((p, i) => { const [a, c] = p.split(',').map(Number);
      x = i ? x + a : a; y = i ? y + c : c; b[0] = Math.min(b[0], x / Q); b[1] = Math.min(b[1], y / Q); b[2] = Math.max(b[2], x / Q); b[3] = Math.max(b[3], y / Q); }); }
    return { id: m.file.replace(/^\d+_|\.svg$/g, ''), name: t, w: m.w, h: m.h, b, r: enc };
  });
  const body = marks.map(m => '  { id: ' + JSON.stringify(m.id) + ', name: ' + JSON.stringify(m.name) + ', w: ' + m.w +
    ', h: ' + m.h + ', b: ' + JSON.stringify(m.b) + ',\n    r: ' + JSON.stringify(m.r) + ' }').join(',\n');
  return '// GENERATED by tools/livery_marks_prep.js from assets-src/stickers/cut.json (flatten.py) - never hand-edit.\n' +
    '// THE TWELVE ALASKA MARKS (LIVERY-STICKERS, 9 Nov 2026), the livery stickers\' geometry: closed rings in the mark\'s own\n' +
    '// units (w x h, y down; b the ink box), a tenth of a unit a step, the first point absolute and the rest deltas; filled even-odd.\n' +
    '// A lazy file: aeroskin.js (AERO_VINYL_MARKS: the same ids, names and sizes) asks for it on the first sticker drawn.\n' +
    '(function () {\n' +
    'var LIVERY_MARKS = { v: 1, unit: ' + (1 / Q) + ', marks: [\n' + body + '\n] };\n' +
    'if (typeof window !== \'undefined\') window.LIVERY_MARKS = LIVERY_MARKS;\n' +
    'if (typeof module !== \'undefined\' && module.exports) module.exports = LIVERY_MARKS;\n' +
    '})();\n';
}
const text = build();
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r/g, '') : '';
  if (cur !== text) { console.log('livery_marks.js is STALE: node tools/livery_marks_prep.js'); process.exit(1); }
  console.log('livery_marks.js fresh (' + text.length + ' bytes)');
} else {
  fs.writeFileSync(OUT, text);
  const M = require(OUT);
  console.log('wrote ' + path.relative(ROOT, OUT) + ': ' + text.length + ' bytes, ' + M.marks.length + ' marks, ' +
    M.marks.reduce((s, m) => s + m.r.reduce((t, r) => t + r.split(' ').length, 0), 0) + ' points');
  for (const m of M.marks) console.log("  { id: '" + m.id + "', name: " + JSON.stringify(m.name) + ', b: ' + JSON.stringify(m.b) + ' },');
}
