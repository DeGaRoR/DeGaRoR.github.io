// the palette names the colour you GET; the neutral map's base is divided out
function paintHex(hex) {
  const r = Math.min(255, Math.round(((hex >> 16) & 255) / PAINT_BASE));
  const g = Math.min(255, Math.round(((hex >> 8) & 255) / PAINT_BASE));
  const b = Math.min(255, Math.round((hex & 255) / PAINT_BASE));
  return (r << 16) | (g << 8) | b;
}

