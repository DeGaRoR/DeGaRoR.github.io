// ---------------------------------------------------------------------------
// THE SITE
// ---------------------------------------------------------------------------
// One plane, tilted two ways. Every post length in the building is a
// subtraction against this — which is the whole reason the stance layer
// exists, and the reason a house on a beach does not look like a house on a
// prairie.
const groundFn = P => (x, z) =>
  -Math.tan(P.slopeX * D2R) * x - Math.tan(P.slopeZ * D2R) * z;

// ---------------------------------------------------------------------------
// THE ROOF, AS PLANES
// ---------------------------------------------------------------------------
// A plane is y = a*x + b*z + c. The surface is min() over all of them, which
// is true for every family here (each is convex from below) and is what makes
// the hip fall out for free instead of being a fifth roof type.
//
// A facet is a QUAD given as [eave0, eave1, top1, top0]. A hip end is the same
// quad with its two top corners coincident. Ribs, fascia, barge and ridge caps
// are all expressed against that one shape, so nothing has to know which
// family it is drawing.
function roofModel(V) {
  const w = V.w, L = V.L, k = Math.tan(V.pitch * D2R);
  const eaveY = V.plateY + V.roofT;           // TOP surface, at the wall line
  const ov = V.eaveOver, rk = V.hip ? V.eaveOver : V.rakeOver;
  const zo = w / 2 + ov, xo = L / 2 + rk;
  const planes = [], facets = [], ridges = [], hips = [], rakes = [];
  const p3 = (x, z, y) => [x, y, z];

  if (V.fam === 1) {                                   // SHED
    const c = eaveY + k * (w / 2);                     // y = c + k*z
    planes.push({ a: 0, b: k, c: c });
    const yAt = z => c + k * z;
    facets.push({ q: [p3(-xo, -zo, yAt(-zo)), p3(xo, -zo, yAt(-zo)),
                      p3(xo, zo, yAt(zo)), p3(-xo, zo, yAt(zo))],
                  eave: [0, 1], top: [3, 2], eaveTrue: true, pitch: V.pitch });
    rakes.push([p3(-xo, -zo, yAt(-zo)), p3(-xo, zo, yAt(zo))]);
    rakes.push([p3(xo, -zo, yAt(-zo)), p3(xo, zo, yAt(zo))]);
  } else if (V.fam === 2) {                            // SALTBOX
    const zr = V.ridgeF * (w / 2);
    const k2 = Math.tan(V.pitch2 * D2R);
    const ridgeY = eaveY + k * (w / 2 - zr);
    planes.push({ a: 0, b: -k, c: ridgeY + k * zr });   // front (+z)
    planes.push({ a: 0, b: k2, c: ridgeY - k2 * zr });  // rear (-z)
    const yF = z => ridgeY - k * (z - zr), yB = z => ridgeY + k2 * (z - zr);
    facets.push({ q: [p3(-xo, zo, yF(zo)), p3(xo, zo, yF(zo)),
                      p3(xo, zr, ridgeY), p3(-xo, zr, ridgeY)],
                  eave: [0, 1], top: [3, 2], eaveTrue: true, pitch: V.pitch });
    facets.push({ q: [p3(xo, -zo, yB(-zo)), p3(-xo, -zo, yB(-zo)),
                      p3(-xo, zr, ridgeY), p3(xo, zr, ridgeY)],
                  eave: [0, 1], top: [3, 2], eaveTrue: true, pitch: V.pitch2 });
    ridges.push([p3(-xo, zr, ridgeY), p3(xo, zr, ridgeY)]);
    for (const s of [-1, 1]) rakes.push([p3(s * xo, zo, yF(zo)),
                                         p3(s * xo, zr, ridgeY)],
                                        [p3(s * xo, zr, ridgeY),
                                         p3(s * xo, -zo, yB(-zo))]);
  } else if (V.fam === 3) {                            // GAMBREL
    const zb = V.brkF * (w / 2), k2 = Math.tan(V.pitch2 * D2R);
    const brkY = eaveY + k2 * (w / 2 - zb);
    const ridgeY = brkY + k * zb;
    planes.push({ a: 0, b: -k, c: ridgeY }, { a: 0, b: k, c: ridgeY },
                 { a: 0, b: -k2, c: brkY + k2 * zb },
                 { a: 0, b: k2, c: brkY + k2 * zb });
    const yLow = z => brkY + k2 * (zb - Math.abs(z));
    for (const s of [1, -1]) {
      facets.push({ q: [p3(-s * xo, s * zo, yLow(zo)), p3(s * xo, s * zo, yLow(zo)),
                        p3(s * xo, s * zb, brkY), p3(-s * xo, s * zb, brkY)],
                    eave: [0, 1], top: [3, 2], eaveTrue: true, pitch: V.pitch2 });
      facets.push({ q: [p3(-s * xo, s * zb, brkY), p3(s * xo, s * zb, brkY),
                        p3(s * xo, 0, ridgeY), p3(-s * xo, 0, ridgeY)],
                    eave: [0, 1], top: [3, 2], eaveTrue: false,
                    pitch: V.pitch });
      for (const sx of [-1, 1]) {
        rakes.push([p3(sx * xo, s * zo, yLow(zo)), p3(sx * xo, s * zb, brkY)]);
        rakes.push([p3(sx * xo, s * zb, brkY), p3(sx * xo, 0, ridgeY)]);
      }
    }
    ridges.push([p3(-xo, 0, ridgeY), p3(xo, 0, ridgeY)]);
  } else {                                             // GABLE (+ hip ends)
    const ridgeY = eaveY + k * (w / 2);
    planes.push({ a: 0, b: -k, c: ridgeY }, { a: 0, b: k, c: ridgeY });
    const xh = V.hip ? Math.max(0, L / 2 - w / 2) : xo;
    if (V.hip) planes.push({ a: -k, b: 0, c: ridgeY + k * xh },
                           { a: k, b: 0, c: ridgeY + k * xh });
    const yS = z => ridgeY - k * Math.abs(z);
    for (const s of [1, -1])
      facets.push({ q: [p3(-s * xo, s * zo, yS(zo)), p3(s * xo, s * zo, yS(zo)),
                        p3(s * xh, 0, ridgeY), p3(-s * xh, 0, ridgeY)],
                    eave: [0, 1], top: [3, 2], eaveTrue: true, pitch: V.pitch });
    if (V.hip) {
      for (const s of [1, -1])
        facets.push({ q: [p3(s * xo, s * zo, yS(zo)), p3(s * xo, -s * zo, yS(zo)),
                          p3(s * xh, 0, ridgeY), p3(s * xh, 0, ridgeY)],
                      eave: [0, 1], top: [3, 2], eaveTrue: true, pitch: V.pitch });
      for (const sx of [-1, 1]) for (const sz of [-1, 1])
        hips.push([p3(sx * xo, sz * zo, yS(zo)), p3(sx * xh, 0, ridgeY)]);
      if (xh > 1e-3) ridges.push([p3(-xh, 0, ridgeY), p3(xh, 0, ridgeY)]);
    } else {
      ridges.push([p3(-xo, 0, ridgeY), p3(xo, 0, ridgeY)]);
      for (const sx of [-1, 1]) for (const sz of [-1, 1])
        rakes.push([p3(sx * xo, sz * zo, yS(sz * zo)), p3(sx * xo, 0, ridgeY)]);
    }
  }

  const topAt = (x, z) => {
    let y = Infinity;
    for (const p of planes) y = Math.min(y, p.a * x + p.b * z + p.c);
    return y;
  };
  const underAt = (x, z) => topAt(x, z) - V.roofT;
  let ridgeY = -Infinity;
  for (const f of facets) for (const p of f.q) ridgeY = Math.max(ridgeY, p[1]);
  return { planes, facets, ridges, hips, rakes, topAt, underAt,
           ridgeY, eaveY, xo, zo };
}

// Where a wall's top changes slope: the s along A->B at which two roof planes
// swap places. Solved, not sampled — the wall then has an exact vertex on the
// ridge instead of a chord across it.
function wallSplits(R, A, B) {
  const dx = B[0] - A[0], dz = B[1] - A[1];
  const L = Math.hypot(dx, dz);
  const out = [];
  const at = (p, s) => p.a * (A[0] + dx * s / L) + p.b * (A[1] + dz * s / L) + p.c;
  for (let i = 0; i < R.planes.length; i++)
    for (let j = i + 1; j < R.planes.length; j++) {
      const p = R.planes[i], q = R.planes[j];
      const d0 = at(p, 0) - at(q, 0), d1 = at(p, L) - at(q, L);
      if (Math.abs(d1 - d0) < 1e-9) continue;
      const s = -d0 / (d1 - d0) * L;
      if (s <= 1e-3 || s >= L - 1e-3) continue;
      const x = A[0] + dx * s / L, z = A[1] + dz * s / L;
      if (Math.abs(at(p, s) - R.topAt(x, z)) < 1e-6) out.push(s);
    }
  return out;
}

// ---------------------------------------------------------------------------
// OPENINGS
// ---------------------------------------------------------------------------
// Windows are laid out per WALL and per STOREY: n of them evenly spaced along
// the run, at the sill height above each floor. A window that would break out
// through the roof line (a gable end, a shed's low side) is DROPPED, not
// clipped — the count of dropped openings is an instrument on the bench, and a
// build that drops six of them is telling you the wall is too short.
function openingsFor(P, V, R, side, A, B, opts) {
  const o = opts || {};
  const L = Math.hypot(B[0] - A[0], B[1] - A[1]);
  const holes = [];
  let dropped = 0;
  const at = s => { const t = s / L;
    return R.underAt(A[0] + (B[0] - A[0]) * t, A[1] + (B[1] - A[1]) * t); };
  const fits = (s0, s1, y1) => {
    const N = 5;
    for (let i = 0; i <= N; i++)
      if (at(s0 + (s1 - s0) * i / N) < y1 + 0.10) return false;
    return true;
  };
  // the door first: it owns its slot and a window may not stand in it
  let door = null;
  if (o.door) {
    const c = (o.doorPos === undefined ? clamp(P.doorPos, 0.05, 0.95)
                                       : o.doorPos) * L;
    const s0 = clamp(c - P.doorW / 2, 0.08, L - P.doorW - 0.08);
    const h = { s0: s0, s1: s0 + P.doorW, y0: V.floorY - 0.005,
                y1: V.floorY + P.doorH, kind: 'door' };
    if (fits(h.s0, h.s1, h.y1)) { holes.push(h); door = h; } else dropped++;
  }
  // THE BAY'S OWN HOLE. It is not a window — nothing is glazed here and no
  // casing goes round it; the bay's three walls stand in the gap and close it.
  // It is pushed first so the window loop treats it the way it treats a door.
  let bayH2 = null;
  if (o.bay) {
    bayH2 = { s0: o.bay.s0, s1: o.bay.s1, y0: o.bay.y0 + 0.04,
              y1: o.bay.head, kind: 'bay' };
    holes.push(bayH2);
  }
  const n = Math.round(o.n || 0);
  for (let st = 0; st < P.storeys; st++) {
    const y0 = V.floorY + st * P.floorH + P.winSill;
    for (let i = 0; i < n; i++) {
      const c = (i + 0.5) / n * L;
      const h = { s0: c - P.winW / 2, s1: c + P.winW / 2,
                  y0: y0, y1: y0 + P.winH, kind: 'window' };
      if (h.s0 < 0.15 || h.s1 > L - 0.15) { dropped++; continue; }
      if (door && st === 0 && h.s1 > door.s0 - 0.22 && h.s0 < door.s1 + 0.22) {
        dropped++; continue;
      }
      if (bayH2 && h.s1 > bayH2.s0 - 0.22 && h.s0 < bayH2.s1 + 0.22 &&
          h.y0 < bayH2.y1 && h.y1 > bayH2.y0) { dropped++; continue; }
      if (!fits(h.s0, h.s1, h.y1)) { dropped++; continue; }
      // and it must not be where the porch roof lands on this wall
      if (o.band && h.s1 > o.band.s0 && h.s0 < o.band.s1 &&
          h.y1 > o.band.y0 && h.y0 < o.band.y1) { dropped++; continue; }
      holes.push(h);
    }
  }
  // the attic light in a gable end, sized to what the triangle can hold
  if (o.gable && P.gableWin) {
    const y0 = V.plateY + 0.30;
    const wgt = Math.min(0.9, P.winW * 0.7), hgt = Math.min(0.8, P.winH * 0.6);
    const h = { s0: L / 2 - wgt / 2, s1: L / 2 + wgt / 2, y0: y0,
                y1: y0 + hgt, kind: 'window' };
    if (fits(h.s0, h.s1, h.y1)) holes.push(h); else dropped++;
  }
  return { holes, dropped };
}

// The joinery that makes an opening read as one: casing on three sides, a
// projecting sill under it, and (lod 0) a sash bar or two. Drawn on the
// EXTERIOR face only — nothing inside is ever seen through 55% glass.
// WHICH WINDOWS ARE LIT (the user: "interior lights, only the window textures
// to become emissive ... turn on independently (or linked)"). One switch, or
// each window its own: hashed from the window's OWN place on its wall and the
// seed, so the same house lights the same rooms every build and a slider on
// the seed walks through the neighbours' habits. The share is a probability,
// not a count — a house with one window lit at 0.6 is a house whose one
// occupant is in.
function litFor(P, W, h) {
  if (!P.lights) return 0;
  if (P.winLink) return 1;
  const a = W.A || [0, 0];
  const hh = Math.sin(a[0] * 12.9898 + a[1] * 78.233 + h.s0 * 3.71 +
                      h.y0 * 5.13 + (P.lightSeed | 0) * 0.77) * 43758.5453;
  return (hh - Math.floor(hh)) < (P.winLit === undefined ? 0.6 : P.winLit) ? 1 : 0;
}

function dressOpening(bags, P, Q, W, h, y1) {
  if (h.kind === 'bay') return;      // the bay's own walls are its finish
  const t = P.trimW, X = W.X, N = W.N;
  const pr = 0.022;                          // trim stands proud of the siding
  const p = (s, y) => add(W.P(s, y, 1), mul(N, pr));
  if (Q.lod === 0 && t > 0.004) {
    const th = 0.028;
    // A CASING IS THERE TO HIDE THE CUT (the user: "the finish below the
    // window ... should be higher, so it hides the thickness of the wall.
    // That's the case with all finishes, which you have placed too far from
    // the opening. They're meant at masking the 'cut' part of the window
    // opening in the wall, so they should cover them").
    //
    // So every board LAPS INTO the opening by `ov` rather than stopping at its
    // edge, and the sill's TOP sits above the opening's bottom — which is what
    // hides the sill reveal, the one cut you look straight down onto.
    //
    // The head and the sill also had their section the wrong way round: a
    // `beam`'s hw runs along X x U, which for a horizontal board is the WALL
    // NORMAL. They were 110 mm thick and 56 mm tall; they are 28 mm thick and
    // 110 mm tall now, like the jambs beside them.
    const ov = 0.030;
    // HOW THE THREE BOARDS MEET, and it should not always be the same (the
    // user: "You make the beam structure of the window outline cross each
    // other now. That's nice, but that should not be systematic, most of the
    // time, they should just meet right, or stick only on one axis"). Three
    // joints, chosen deterministically per opening:
    //   0  the head runs the full width and the jambs die under it — the
    //      plain joint, and the common one
    //   1  the jambs run past the head, which caps between them
    //   2  the head laps over with a horn each side — the crossed look, kept
    //      for one opening in five
    const jh = ((Math.round(h.s0 * 977) ^ Math.round(h.y0 * 613)) >>> 0) % 10;
    const joint = jh < 5 ? 0 : (jh < 8 ? 1 : 2);
    const headOut = joint === 2 ? t * 1.15 : (joint === 0 ? t / 2 : 0);
    const jambTop = joint === 1 ? y1 + t : y1 + (joint === 0 ? -0.004 : 0.004);
    const headY = y1 + t / 2 - ov;
    // the casing is milled stock and takes the same small chamfer the posts
    // do — on a 100 mm board it is the arris that catches the light and tells
    // you there is a board there at all
    const bev = BEV(P, Q);
    beam(bags.trim, p(h.s0 - t / 2 + ov, h.y0 - t), p(h.s0 - t / 2 + ov, jambTop),
         t / 2, th, N, 0, bev);
    beam(bags.trim, p(h.s1 + t / 2 - ov, h.y0 - t), p(h.s1 + t / 2 - ov, jambTop),
         t / 2, th, N, 0, bev);
    beam(bags.trim, p(h.s0 - headOut, headY), p(h.s1 + headOut, headY),
         th, t / 2, [0, 1, 0], 0, bev);
    if (h.kind === 'window') {
      // the sill: proud of the casing, and high enough to cap the reveal
      const sy = h.y0 + 0.030;
      beam(bags.trim, add(p(h.s0 - t * 1.3, sy), mul(N, 0.016)),
           add(p(h.s1 + t * 1.3, sy), mul(N, 0.016)), 0.034, t * 0.42,
           [0, 1, 0], 0, bev);
    }
  }
  if (h.kind === 'door') {
    buildDoor(bags, P, Q, W, h, y1);
    // the lamp goes on the side of the door with wall to spare
    buildLamp(bags, P, Q, W, h, h.s0 > W.L - h.s1 ? -1 : 1);
    return;
  }
  // the glass: one pane in the reveal, plus sash bars
  // A SASH IS SET NEAR THE FACE OF THE WALL, not halfway through it: the
  // reveal is on the INSIDE of the glass, which is what gives a window its
  // shadow line from outside (the user: "The windows should sit towards the
  // exterior wall, not in the middle of the wall depth").
  const gd = 0.78;
  const g0 = W.P(h.s0 + 0.03, h.y0 + 0.03, gd);
  const g1 = W.P(h.s1 - 0.03, h.y0 + 0.03, gd);
  const g2 = W.P(h.s1 - 0.03, y1 - 0.03, gd);
  const g3 = W.P(h.s0 + 0.03, y1 - 0.03, gd);
  const lit = litFor(P, W, h);
  bags.glass.setGlow(lit);
  face(bags.glass, [g0, g1, g2, g3], N,
       uvFrame(g0, X, [0, 1, 0]));
  bags.glass.setGlow(0);
  LIT_LOG.panes++;
  if (lit) LIT_LOG.windows++;
  if (Q.lod === 0 && P.muntin) {
    const cS = (h.s0 + h.s1) / 2, cY = (h.y0 + y1) / 2;
    // the sash bars: the vertical one is the piece of finish a face gets
    // closest to, and it was the one with no arris on it at all
    const mb = BEV(P, Q);
    beam(bags.trim, W.P(cS, h.y0 + 0.02, 0.86), W.P(cS, y1 - 0.02, 0.86),
         0.018, 0.016, N, 0, mb);
    beam(bags.trim, W.P(h.s0 + 0.02, cY, 0.86), W.P(h.s1 - 0.02, cY, 0.86),
         0.018, 0.016, N, 0, mb);
  }
}

// THE DECK'S OWN PLAN, so the door can be put ON it (the user: "door not
// constrained enough to sit on the porch" and "Synchronize placement of the
// little porch roofs, entrance door and front terrace"). buildDeck draws from
// this, the door is clamped into it, and the canopy is centred on the door —
// one plan, three consumers, no drift.
function deckPlan(P, V) {
  if (!P.porch) return null;
  const half = V.wallT / 2;
  const zIn = V.w / 2 - half;
  const dl = Math.min(V.L * P.porchLenF, V.L + 2 * P.porchD);
  const cx = P.porchOff * V.L / 2;
  return { x0: cx - dl / 2, x1: cx + dl / 2, cx: cx, dl: dl,
           zIn: zIn, zOut: zIn + P.porchD, yTop: V.floorY - 0.02 };
}

// where the front door ends up, as a FRACTION along the front wall: on the
// deck if there is one, and far enough in for its casing to clear the corner
function doorPosOf(P, V) {
  const dk = deckPlan(P, V);
  let x = (clamp(P.doorPos, 0.05, 0.95) - 0.5) * V.L;
  if (dk) {
    const m = P.doorW / 2 + 0.45;
    if (dk.x1 - dk.x0 > P.doorW + 1.0)
      x = clamp(x, dk.x0 + m, dk.x1 - m);
  }
  x = clamp(x, -V.L / 2 + P.doorW / 2 + 0.35, V.L / 2 - P.doorW / 2 - 0.35);
  return x / V.L + 0.5;
}

// WHERE THE PORCH ROOF MEETS THE WALL — computed BEFORE the openings are laid
// out, because the two have to agree (the user: "the porch cover is often
// within a window, it would need to be synchronized"). buildDeck draws it from
// the same function, so there is one answer and not two.
function porchRoofPlan(P, V) {
  if (!P.porch || !P.porchRoof) return null;
  const half = V.wallT / 2;
  const zIn = V.w / 2 - half;
  const dl = Math.min(V.L * P.porchLenF, V.L + 2 * P.porchD);
  const cx = P.porchOff * V.L / 2;
  const x0 = cx - dl / 2, x1 = cx + dl / 2;
  const isCanopy = Math.round(P.porchRoof) === 1;
  const cW = isCanopy ? Math.max(1.4, P.doorW + 1.0) : dl + 0.3;
  const cX = isCanopy
    ? clamp((doorPosOf(P, V) - 0.5) * V.L, x0 + cW / 2, x1 - cW / 2) : cx;
  const yWall = isCanopy
    ? Math.min(V.plateY - 0.10, V.floorY + P.doorH + 0.55)
    : Math.min(V.plateY - 0.10, V.floorY + P.floorH + 0.25);
  const depth = isCanopy ? Math.min(P.porchD, 1.35) : P.porchD + 0.25;
  return { cX: cX, cW: cW, yWall: yWall, depth: depth, zIn: zIn,
           x0: x0, x1: x1, dl: dl, canopy: isCanopy, deckTop: V.floorY - 0.02 };
}

// ---------------------------------------------------------------------------
// A VOLUME: walls, floor, roof
// ---------------------------------------------------------------------------
function buildVolume(bags, P, Q, V, R, plan, wallOpts) {
  const t = V.wallT;
  const drop = [];
  const kept = [];
  for (let i = 0; i < plan.length; i++) {
    const A = plan[i], B = plan[(i + 1) % plan.length];
    const o = wallOpts[i] || {};
    if (o.skip) continue;
    // AN OPEN SIDE. A woodshed is a roof, three walls and a post — the fourth
    // side is posts and a header, because the whole point of it is that you
    // can throw a load of rounds in from the truck.
    if (o.open) {
      const Lo = Math.hypot(B[0] - A[0], B[1] - A[1]);
      const yH = R.underAt((A[0] + B[0]) / 2, (A[1] + B[1]) / 2);
      const n = Math.max(2, Math.round(Lo / 2.2));
      for (let j = 0; j <= n; j++) {
        const u = j / n;
        const x = A[0] + (B[0] - A[0]) * u, z = A[1] + (B[1] - A[1]) * u;
        beam(bags.post, [x, V.floorY - 0.10, z], [x, yH - 0.10, z],
             t * 0.55, t * 0.55, [0, 0, 1], 0,
             { uv: jog(x, z, 9), bevel: Q.lod === 0 ? P.bevel : 0 });
      }
      beam(bags.deck, [A[0], yH - 0.06, A[1]], [B[0], yH - 0.06, B[1]],
           t * 0.5, 0.11, [0, 1, 0]);
      continue;
    }
    const op = openingsFor(P, V, R, i, A, B, o);
    drop.push(op.dropped);
    {
      // publish what SURVIVED, in the wall's own coordinates plus the roof
      // limit over each jamb: GATE HOUSE reads these, and so does the bench's
      // openings line. A generator that keeps a window it cannot fit is
      // exactly the failure this makes visible.
      const Lw = Math.hypot(B[0] - A[0], B[1] - A[1]);
      const uAt = s => R.underAt(A[0] + (B[0] - A[0]) * s / Lw,
                                 A[1] + (B[1] - A[1]) * s / Lw);
      for (const h of op.holes)
        kept.push({ side: i, wallL: Lw, s0: h.s0, s1: h.s1, y0: h.y0,
                    y1: h.y1, kind: h.kind,
                    underA: uAt(h.s0), underB: uAt(h.s1) });
    }
    const holes = Q.lod === 0 ? op.holes : [];
    const Lw = Math.hypot(B[0] - A[0], B[1] - A[1]);
    const nO = [-(B[1] - A[1]) / Lw, (B[0] - A[0]) / Lw];   // outward, in plan
    const W = wall(bags.siding, {
      A: A, B: B, y0: V.floorY - 0.10, t: t,
      // half a thickness past each corner: four panels on their own
      // centrelines otherwise leave a t/2 notch at every corner, which is the
      // gap that opens whenever a dimension changes
      ext: [t / 2, t / 2],
      // read at the FACE, not the centreline: under a pitched roof the outer
      // top of a thick wall is cut higher than the inner one
      topAt: (s, side) => R.underAt(
        A[0] + (B[0] - A[0]) * s / Lw + nO[0] * (t / 2) * side,
        A[1] + (B[1] - A[1]) * s / Lw + nO[1] * (t / 2) * side),
      holes: holes, splits: wallSplits(R, A, B),
      // the far mesh keeps its inner faces: without them you see through the
      // building from any angle that catches an open edge, which is what the
      // user noticed about lod 1
      inner: true, capTop: Q.lod === 0, capBot: Q.lod === 0,
      endCap: [false, false],
      sub: Q.lod === 0 ? (P.aoRange || 0.55) * 0.85 : 0,
    });
    if (!W) continue;
    if (Q.lod === 0) {
      for (const h of op.holes)
        dressOpening(bags, P, Q, W, h,
                     Math.min(h.y1, R.underAt(
                       (A[0] + B[0]) / 2, (A[1] + B[1]) / 2)));
    } else {
      // lod 1: THE OPENING KEEPS ITS FINISH (the user: "The low poly version
      // should keep a low poly detail for the finish of the windows/doors").
      // A frame board round the hole and one opaque panel in it — fourteen
      // triangles that read as a window from anywhere, and no transparency to
      // sort.
      for (const h of op.holes) {
        if (h.kind === 'bay') continue;      // the bay is drawn, not glazed
        const y1 = h.y1, fr = 0.075;
        const cY = (h.y0 + y1) / 2;
        const a = W.P(h.s0 - fr, cY, 1), b = W.P(h.s1 + fr, cY, 1);
        beam(bags.trim, add(a, mul(W.N, 0.010)), add(b, mul(W.N, 0.010)),
             0.026, (y1 - h.y0) / 2 + fr, [0, 1, 0]);
        const p = (s, y) => add(W.P(s, y, 1), mul(W.N, 0.040));
        if (h.kind !== 'door') bags.pane.setGlow(litFor(P, W, h));
        face(h.kind === 'door' ? bags.trim : bags.pane,
             [p(h.s0, h.y0), p(h.s1, h.y0), p(h.s1, y1), p(h.s0, y1)], W.N,
             uvFrame(p(h.s0, h.y0), W.X, [0, 1, 0]));
        bags.pane.setGlow(0);
      }
    }
    // corner boards: the vertical straps that make a painted board house read
    if (P.trimW > 0.004 && Math.round(P.corner) === 0) {
      const cA = add(W.P(0.001, V.floorY - 0.10, 1), mul(W.N, 0.02));
      const top = R.underAt(A[0], A[1]);
      beam(bags.trim, cA, [cA[0], top, cA[2]], P.trimW * 0.85, 0.030, W.N, 0,
           { bevel: Q.lod === 0 ? P.bevel : 0 });
    }
  }
  return { dropped: drop.reduce((a, b) => a + b, 0), openings: kept };
}

// ---------------------------------------------------------------------------
// HOW THE WALLS MEET AT A CORNER (the user: "When choosing the logs, you may
// want to have appropriate architecture; either logs on the sides, or log's
// ends alternating and crossing. The current combination looks odd")
// ---------------------------------------------------------------------------
// The odd combination was a wall at LOG SCALE finished like a boarded one: a
// milled corner strap, painted, covering a joint that a log wall does not
// have. A log wall cannot be mitred and cannot be strapped — it is STACKED,
// and the two walls that meet at a corner have to take turns. One course
// belongs to the wall running one way and its sawn end stands out past the
// corner; the next course belongs to the other wall and stands out the other
// way. That alternation is the corner: it is what stops the two walls racking
// apart, and it is what tells you at fifty metres that a building is logs.
//
// So the corner became a choice of three, and each is a whole architecture:
//   corner boards      milled stock, a board house, the strap covers the joint
//   crossed log ends   a log house — the ends alternate and cross
//   plain              the claddings simply meet, which is a shed
//
// The ends are drawn every other course in the far mesh, which keeps the
// outline (the gate holds both meshes to one silhouette) at half the cost.
function buildLogCorners(bags, P, Q, V, R, plan) {
  const c = clamp(P.logD === undefined ? 0.24 : P.logD, 0.12, 0.45);
  const out = clamp(P.logOut === undefined ? 0.24 : P.logOut, 0.06, 0.60);
  const y0 = V.floorY - 0.06;
  const hw = Math.max(V.wallT, c) / 2;
  const step = Q.lod === 0 ? 1 : 2;
  for (let i = 0; i < plan.length; i++) {
    const C = plan[i];
    const A = plan[(i + plan.length - 1) % plan.length];
    const B = plan[(i + 1) % plan.length];
    const dA = nrm([C[0] - A[0], 0, C[1] - A[1]]);        // arrives at C
    const dB = nrm([B[0] - C[0], 0, B[1] - C[1]]);        // leaves C
    // the topmost course has to stay under the roof, like every other wall
    const top = R.underAt(C[0], C[1]) - c * 0.6;
    const n = Math.floor((top - y0) / c);
    for (let k = 0; k < n; k += step) {
      const y = y0 + (k + 0.5) * c;
      const d = (k % 2 === 0) ? dA : mul(dB, -1);
      beam(bags.siding, [C[0] - d[0] * hw, y, C[1] - d[2] * hw],
           [C[0] + d[0] * out, y, C[1] + d[2] * out], hw, c * 0.46,
           [0, 1, 0], 0, { uv: [(k * 0.37) % 1.7, y] });
    }
  }
}

// The roof itself: one plate per facet, then the metal on top of it. Standing
// seams run UP THE SLOPE from the eave edge to the top edge of the facet, so
// they converge correctly on a hip end (whose top edge is one point) without
// a line of code that knows what a hip is.
// A BOARD ON A FACE, which is what a fascia and a barge board both are: a
// plank standing in the vertical plane through an edge, its OUTER face proud
// of that edge and its body going inward. The first cut of this bench centred
// the board ON the edge line, so half of every fascia was buried in the roof
// slab and half hung off nothing — the junction the user called out. Drawn
// this way the board's outer face IS the roof's outer face, and it covers the
// slab's cut edge instead of arguing with it.
function faceBoard(bag, p0, p1, dropH, thick, out) {
  const o = mul(out, thick);
  const a = add(p0, o), b = add(p1, o);
  const ring = [a, b, [b[0], b[1] - dropH, b[2]], [a[0], a[1] - dropH, a[2]]];
  // mapped in the board's own plane, like every other rim board (G234): u
  // along the run, v across it, so a raking board is not a squashed vertical
  // projection of a level one
  const eu = nrm(sub(b, a));
  let dv = nrm(crs(eu, mul(out, -1)));
  if (dv[1] < 0) dv = mul(dv, -1);
  plate(bag, ring, thick, mul(out, -1), uvFrame(ring[3], eu, dv));
}

// ---------------------------------------------------------------------------
// THE EDGE OF ANY ROOF (the user: "there are still significant issues around
// the borders of the roofs, all types now. Take a back step on that one, and
// ensure that all roofs are properly closed with their finish.")
// ---------------------------------------------------------------------------
// THE BACK STEP: there were four roofs in this generator — the main facets,
// the dormers', the lean-to's and the porch's — and only the first had any
// edge treatment at all. Every one of them is a QUAD, so every one of them can
// be finished by the same function: hand it the four corners and say which
// edges are free, and it lays a mitred, closed rim round exactly those.
//
// `free` is a four-flag array in corner order (q0-q1, q1-q2, q2-q3, q3-q0).
// An edge that dies into a wall gets no board — that is a flashing, not a
// fascia — and an edge shared with another facet gets none either.
let RIM_LOG = null;      // build() collects what was finished, for the gate

function roofRim(bag, q, free, drop, thick) {
  if (RIM_LOG) RIM_LOG.push({ q: q.map(p2 => p2.slice()), free: free.slice() });
  const c = K.ringCentre(q);
  const runs = [];
  let cur = null;
  for (let i = 0; i < 4; i++) {
    const a = q[i], b = q[(i + 1) % 4];
    if (!free[i] || len(sub(a, b)) < 0.05) { cur = null; continue; }
    const mid = K.lerp3(a, b, 0.5);
    let o = [mid[0] - c[0], 0, mid[2] - c[2]];
    if (len(o) < 1e-4) o = [0, 0, 1]; else o = nrm(o);
    if (cur && len(sub(cur.pts[cur.pts.length - 1], a)) < 0.02) {
      cur.pts.push(b); cur.outs.push(o);
    } else {
      cur = { pts: [a, b], outs: [o] };
      runs.push(cur);
    }
  }
  // a run that comes all the way round joins its own tail
  for (const r of runs) {
    const closed = r.pts.length > 4 &&
                   len(sub(r.pts[0], r.pts[r.pts.length - 1])) < 0.02;
    K.rimLoop(bag, r.pts, r.outs, drop, thick, closed);
  }
}

// WHICH ROOFS GET DRAWN STANDING SEAMS, and it is the covering that decides
// (the user, of a shake roof carrying a full set of them: "the attached house
// has a significant issue with its roof"). A standing seam is where two sheets
// of METAL are folded together and stood up; shakes, shingles and tiles do not
// have one and cannot. Two ways to get it wrong and both were live: a RIBBED
// set already contains its corrugation in the map, so drawing seams over it is
// two sets of ribs at two pitches; and a shake roof is not sheet at all.
//
// So the sets that take drawn seams are named, not guessed — mirrored from the
// library the way SET_KIND is, because the generator has to be right with no
// payload loaded, and GATE HOUSE holds the two against each other: every key
// here must be a roof set that is metal and NOT ribbed, and no roof set
// outside it may be.
const SET_SEAM = { galv: 1, rust: 1 };
const seamsOn = P => !!SET_SEAM[setFor(P, 'roof')];

// horizontal, away from the ridge: the direction the eave sheds into
function eaveOut(f) {
  const em = K.lerp3(f.q[0], f.q[1], 0.5), tm = K.lerp3(f.q[3], f.q[2], 0.5);
  const d = [em[0] - tm[0], 0, em[2] - tm[2]];
  return len(d) < 1e-6 ? [0, 0, 1] : nrm(d);
}

function buildRoof(bags, P, Q, V, R, dorms) {
  const ribbed = setRibbed(setFor(P, 'roof'));
  for (const f of R.facets) {
    const q = f.q;
    const mine = (dorms || []).filter(d => d.f === f);
    if (mine.length && Q.lod === 0) roofFacetHoles(bags.roof, f, V, mine, P);
    else plate(bags.roof, q, V.roofT, [0, -1, 0],
               uvFrame(q[0], nrm(sub(q[1], q[0])), nrm(sub(q[3], q[0]))),
               { sub: Q.lod === 0 ? 1.1 : 0 });
    if (Q.lod !== 0) continue;
    const e0 = q[0], e1 = q[1], t1 = q[2], t0 = q[3];
    if (P.ribs && seamsOn(P) && P.ribPitch > 0.05) {
      const runW = len(sub(e1, e0));
      const n = Math.max(1, Math.round(runW / P.ribPitch));
      const up = [0, 1, 0];
      for (let i = 0; i <= n; i++) {
        const u = i / n;
        const a = K.lerp3(e0, e1, u), b = K.lerp3(t0, t1, u);
        if (len(sub(a, b)) < 0.05) continue;
        // a seam does not cross a dormer: stop it at the front wall
        const cut = mine.find(d => a[0] > d.cx - d.hw && a[0] < d.cx + d.hw);
        const bb = cut ? [a[0], cut.yf, cut.zf] : b;
        if (len(sub(a, bb)) < 0.05) continue;
        beam(bags.rib, off(a, up, P.ribH * 0.5), off(bb, up, P.ribH * 0.5),
             0.016, P.ribH * 0.5, up);
      }
    }
    // THE EAVE ASSEMBLY, and only on a TRUE eave: a gambrel's break line is
    // the bottom edge of the upper facet and gets neither fascia nor soffit,
    // because no water leaves the roof there.
    if (!f.eaveTrue) continue;
    const out = eaveOut(f);
    /* the eave board is part of the rim below */
    // THE SOFFIT closes the overhang. Without it the roof's underside is open
    // from below and you see straight up between the rafters and the wall —
    // the other half of the junction the user asked about.
    const d = P.eaveOver - V.wallT / 2;
    if (d > 0.05) {
      const yS = e0[1] - V.roofT - P.fascia + 0.012;
      const io2 = mul(out, -d);
      const s0 = [e0[0] + io2[0], yS, e0[2] + io2[2]];
      const s1 = [e1[0] + io2[0], yS, e1[2] + io2[2]];
      plate(bags.trim, [[e0[0], yS, e0[2]], [e1[0], yS, e1[2]], s1, s0],
            0.020, [0, -1, 0],
            uvFrame(s0, nrm(sub(e1, e0)), mul(out, -1)));
    }
  }
  if (Q.lod !== 0) return;
  // THE RIM, ROUND EVERY EDGE THAT HAS A FREE ONE (the user: "some geometry
  // remains open ... angled roof", and "barn roof lacks finish on top, the
  // cranked part"). The first cut boarded the eave and the two rakes of a TRUE
  // eave facet only, which left three edges bare: the high edge of a
  // mono-pitch roof, the rakes of a gambrel's upper facet, and the break line
  // where its two slopes meet. An edge is finished unless another facet is
  // already there — the ridge, and the gambrel's break seen from below.
  const facetShares = (f, a, b) => {
    for (const g of R.facets) {
      if (g === f) continue;
      for (let i = 0; i < 4; i++) {
        const c = g.q[i], d2 = g.q[(i + 1) % 4];
        if ((len(sub(a, c)) < 0.02 && len(sub(b, d2)) < 0.02) ||
            (len(sub(a, d2)) < 0.02 && len(sub(b, c)) < 0.02)) return true;
      }
    }
    return false;
  };
  for (const f of R.facets) {
    if (P.fascia <= 0.005) continue;
    const e0 = f.q[0], e1 = f.q[1], t1 = f.q[2], t0 = f.q[3];
    const oe = eaveOut(f);
    // A HIP HAS NO BARGE BOARD: on a hipped roof the side edges are HIP LINES,
    // diagonal in plan, and a vertical board pushed across one is a skewed
    // quad with no texture area on it. A true rake runs square across the eave.
    const rakeDir = nrm([e0[0] - t0[0], 0, e0[2] - t0[2]]);
    const eaveDir = nrm([e1[0] - e0[0], 0, e1[2] - e0[2]]);
    const square = Math.abs(dot(rakeDir, eaveDir)) < 0.08;
    const rake = P.barge > 0.005 && len(sub(t0, t1)) > 0.05 && square;
    const oL = nrm([e0[0] - e1[0], 0, e0[2] - e1[2]]);   // toward the -x end
    const drop = V.roofT + (f.eaveTrue ? P.fascia : P.barge * 0.8);
    const topFree = len(sub(t0, t1)) > 0.05 && !facetShares(f, t0, t1);
    // q order is [e0, e1, t1, t0]: eave, right rake, top, left rake
    roofRim(bags.trim, f.q,
            [f.eaveTrue, rake, topFree, rake], drop, 0.032);
  }
  // THE CRANK. A gambrel's break is a real piece of trim on a real barn — the
  // two pitches meet at an angle no sheet bends round — and without it the
  // upper facet just stops.
  for (const f of R.facets) {
    if (f.eaveTrue || P.barge <= 0.005) continue;
    const e0 = f.q[0], e1 = f.q[1];
    if (len(sub(e0, e1)) < 0.05) continue;
    const oe = eaveOut(f);
    beam(bags.trim, off(off(e0, oe, 0.012), [0, 1, 0], -0.01),
         off(off(e1, oe, 0.012), [0, 1, 0], -0.01),
         0.030, P.barge * 0.42, [0, 1, 0]);
  }
  // A RIDGE CAP IS A PIECE OF FOLDED SHEET. On shakes or tiles the ridge is
  // capped with more of the same material, not with a strip of galvanised —
  // so the metal cap is only drawn on a metal roof, and the material says
  // which is which (the user: "When you choose tiles roofs (and not metal),
  // you should not have roof ridges").
  const roofIsMetal = setMetal(setFor(P, 'roof')) > 0.2;
  if (P.ridgeCap && roofIsMetal) {
    // FOLDED, NOT BOXED (the user: "the roof beams and their joins are very
    // rough"). A ridge cap is one strip of sheet bent down the middle: its
    // section is a shallow inverted V that sits ON the two planes, not a
    // rectangular bar laid across them with its corners in the air. The half
    // angle comes from the roof's own pitch, so a 45-degree roof gets a
    // sharper fold than a 15-degree one, and the ends are cut square with the
    // run rather than left poking past the rake.
    const cap = (e, wid, k) => {
      const L2 = len(sub(e[1], e[0]));
      if (L2 < 0.05) return;
      const drop = wid * k;                       // follow the slope down
      const prof = [[-wid, -drop], [0, 0.012], [wid, -drop],
                    [wid, -drop - 0.014], [0, 0.012 - 0.014],
                    [-wid, -drop - 0.014]];
      K.sweepProfile(bags.metal, off(e[0], [0, 1, 0], 0.004),
                     off(e[1], [0, 1, 0], 0.004), prof, [0, 1, 0], 'shell');
    };
    const kk = Math.tan(clamp(P.pitch, 4, 60) * D2R);
    for (const e of R.ridges) cap(e, 0.115, kk);
    for (const e of R.hips) cap(e, 0.085, kk * 0.75);
  }
}

// ---------------------------------------------------------------------------
// WHAT THE SHED IS FOR
// ---------------------------------------------------------------------------
// The user asked for buildings that are not habitation — storage, and a wood
// reserve. A woodshed with nothing in it is a carport; the cordwood IS the
// building's reason, and it is four rows of rounds against the back wall.
function buildContents(bags, P, Q, V, R) {
  if (!P.firewood) return 0;
  const half = V.wallT / 2;
  const x0 = -V.L / 2 + half + 0.12, x1 = V.L / 2 - half - 0.12;
  const zB = -V.w / 2 + half + 0.12;
  const depth = Math.min(V.w - 2 * half - 0.35, 1.1);
  const top = Math.min(V.floorY + 1.55, R.underAt(0, zB) - 0.25);
  if (top <= V.floorY + 0.3 || x1 - x0 < 0.4) return 0;
  if (Q.lod !== 0) {
    boxAB(bags.deck, [x0, V.floorY, zB], [x1, top, zB + depth]);
    return 1;
  }
  // rounds, stacked: the ends face out, they are all a bit different, and the
  // top course is short because somebody has been burning it
  let seed = 20260908;
  const rnd = () => (seed = (seed * 1664525 + 1013904223) >>> 0) / 4294967296;
  const r = 0.075;
  const rows = Math.floor((top - V.floorY) / (r * 2 + 0.012));
  let n = 0;
  for (let j = 0; j < rows; j++) {
    const y = V.floorY + r + j * (r * 2 + 0.012);
    const last = j === rows - 1;
    const cols = Math.floor((x1 - x0) / (r * 2 + 0.014));
    const use = last ? Math.max(1, Math.round(cols * (0.35 + 0.4 * rnd()))) : cols;
    for (let i = 0; i < use; i++) {
      const x = x0 + r + i * (r * 2 + 0.014) + (rnd() - 0.5) * 0.010;
      const rr = r * (0.80 + 0.34 * rnd());
      cyl(bags.deck, [x, y, zB + 0.02], [0, 0, 1], rr,
          depth * (0.86 + 0.12 * rnd()), 7, true);
      n++;
    }
  }
  return n;
}

// ---------------------------------------------------------------------------
// THE DRAINAGE (the user: "we may want to add a little water drainage from the
// roof, with a pipe going down, classic stuff")
// ---------------------------------------------------------------------------
// A gutter on every TRUE eave, hung on the fascia with its lip below the roof
// edge so the sheet discharges into it rather than over it, and ONE downpipe
// taken off a chosen corner: outlet, swan neck back to the wall face, the
// stack down the wall on straps, and a shoe throwing the water clear.
//
// The stack is cut to THE GROUND UNDER ITS OWN FOOT, like every post in the
// stance layer — on a 12-degree beach a fixed length is either buried in the
// shingle or hanging a metre in the air.
function buildDrainage(bags, P, Q, V, R, g) {
  const out = { gutter: 0, downpipe: null };
  if (!P.gutter) return out;
  const r = P.gutterR, t = 0.004;
  const runs = [];
  for (const f of R.facets) {
    if (!f.eaveTrue) continue;
    const o = eaveOut(f);
    const e0 = f.q[0], e1 = f.q[1];
    const dy = -(V.roofT + Math.max(0.02, P.fascia * 0.35));
    const dx = mul(o, r + 0.028);
    const a = [e0[0] + dx[0], e0[1] + dy, e0[2] + dx[2]];
    const b = [e1[0] + dx[0], e1[1] + dy, e1[2] + dx[2]];
    const prof = Math.round(P.gutter) === 1
      ? K.troughSection(r, t, Q.lod === 0 ? 9 : 4)
      : [[-r, 0], [-r, -r * 1.6], [r, -r * 1.6], [r, 0],
         [r - t, 0], [r - t, -r * 1.6 + t], [-r + t, -r * 1.6 + t], [-r + t, 0]];
    const sw = K.sweepProfile(bags.metal, a, b, prof, [0, 1, 0], 'shell');
    // stop ends: the plate that closes a gutter run, without which you can see
    // down the inside of the trough from the gable end
    if (sw) {
      const h = sw.prof.length / 2;
      K.face(bags.metal, sw.A.slice(0, h), mul(sw.X, -1));
      K.face(bags.metal, sw.B.slice(0, h).reverse(), sw.X);
    }
    out.gutter += len(sub(b, a));
    runs.push({ a: a, b: b, o: o });
    if (Q.lod === 0) {                      // the straps that hold it up
      const L = len(sub(a, b));
      const n = Math.max(1, Math.round(L / 0.95));
      for (let i = 0; i <= n; i++) {
        const p = K.lerp3(a, b, i / n);
        beam(bags.metal, off(p, o, r + 0.02), off(p, o, -r - 0.02),
             0.014, 0.004, [0, 1, 0]);
      }
    }
  }
  if (!P.downpipe || !runs.length) return out;

  // WHICH CORNER. `dpCorner` picks the run and which end of it: a downpipe
  // belongs at a corner of the building, and which corner is a look.
  const idx = Math.round(P.dpCorner) % (runs.length * 2);
  const run = runs[Math.floor(idx / 2) % runs.length];
  const endB = (idx % 2) === 1;
  const pr = P.dpR;
  const head = endB ? run.b : run.a;
  const along = nrm(sub(endB ? run.a : run.b, head));   // back along the gutter
  // BRING IT IN TO THE WALL. The gutter runs to the end of the RAKE, which on
  // a gable is half a metre past the building — a stack dropped at the end of
  // the trough hangs in the air off the corner with its straps reaching for a
  // wall that is not there. Slide it back along the run until it stands
  // against the gable face.
  const p0 = off(off(head, along, pr + 0.06), [0, 1, 0], -0.02);
  const ax = Math.abs(run.o[2]) > 0.5 ? 0 : 2;      // the run's own axis
  const lim = (ax === 0 ? V.L / 2 : V.w / 2) - pr - 0.12;
  p0[ax] = clamp(p0[ax], -lim, lim);
  // the swan neck: out at the gutter, in at the wall. That offset is the
  // overhang plus the trough's own stand-off, less the wall's half thickness.
  const inD = Math.max(0.05, P.eaveOver + r + 0.028 - V.wallT / 2 - pr);
  const wallIn = mul(run.o, -inD);
  const p1 = [p0[0], p0[1] - 0.22, p0[2]];
  const p2 = [p1[0] + wallIn[0], p1[1] - Math.max(0.18, inD * 0.9),
              p1[2] + wallIn[2]];
  const gy = g(p2[0], p2[2]);
  const p3 = [p2[0], Math.min(p2[1] - 0.3, gy + 0.24), p2[2]];
  const shoe = off([p3[0], p3[1], p3[2]], run.o, 0.16);
  const shoeEnd = [shoe[0], p3[1] - 0.13, shoe[2]];
  const seg = Q.lod === 0 ? 10 : 5;
  cyl(bags.metal, p0, [0, -1, 0], pr, len(sub(p0, p1)), seg, true);
  cyl(bags.metal, p1, nrm(sub(p2, p1)), pr, len(sub(p2, p1)), seg, true);
  cyl(bags.metal, p2, [0, -1, 0], pr, Math.max(0.05, p2[1] - p3[1]), seg, true);
  cyl(bags.metal, p3, nrm(sub(shoeEnd, p3)), pr, len(sub(shoeEnd, p3)), seg, true);
  if (Q.lod === 0) {
    // collars over the joints — a pipe run is fittings, not one tube
    for (const j of [p1, p2, p3])
      cyl(bags.metal, off(j, [0, 1, 0], 0.045), [0, -1, 0], pr * 1.18, 0.09,
          seg, true);
    // straps to the wall, every metre and a bit
    const n = Math.max(1, Math.round((p2[1] - p3[1]) / 1.25));
    for (let i = 0; i <= n; i++) {
      const y = p2[1] - (p2[1] - p3[1]) * i / n;
      beam(bags.metal, [p2[0] + run.o[0] * pr, y, p2[2] + run.o[2] * pr],
           [p2[0] - run.o[0] * (pr + 0.07), y, p2[2] - run.o[2] * (pr + 0.07)],
           0.016, 0.004, [0, 1, 0]);
    }
  }
  out.downpipe = { top: p0, foot: p3, shoe: shoeEnd, ground: gy,
                   clear: p3[1] - gy, r: pr };
  return out;
}

// ---------------------------------------------------------------------------
// THE DOOR (G231, the user: "we also need an actual entrance door, right now
// it's a void")
// ---------------------------------------------------------------------------
// It was a hole with a casing round it. A door is a LEAF hung in that hole:
// stiles and rails standing proud of the panels, hinges on one edge, a knob on
// the other, a threshold under it, and — because a door that can stand open is
// worth its forty triangles on a house you walk up to — the whole leaf swings
// about its own hinge line.
//
// The leaf is built in a frame ROTATED ABOUT THE HINGE, so `beam` does all the
// work and no vertex here is placed by hand.
function buildDoor(bags, P, Q, W, h, y1) {
  const up = [0, 1, 0], X = W.X, N = W.N;
  const t = 0.048, gap = 0.005, pr = 0.012, sw = 0.105;
  const wLeaf = (h.s1 - h.s0) - 2 * gap;
  const hLeaf = (y1 - h.y0) - gap;
  if (wLeaf < 0.25 || hLeaf < 0.6) return;
  const ang = clamp(P.doorAjar, 0, 85) * D2R;
  const Xd = nrm([X[0] * Math.cos(ang) + N[0] * Math.sin(ang), 0,
                  X[2] * Math.cos(ang) + N[2] * Math.sin(ang)]);
  const Nd = nrm(crs(Xd, up));
  const hinge = W.P(h.s0 + gap, h.y0, 0.58);      // set toward the outer face
  const yB = h.y0 + gap, yT = yB + hLeaf;
  const a = [hinge[0], (yB + yT) / 2, hinge[2]];
  const b = off(a, Xd, wLeaf);
  beam(bags.trim, a, b, t / 2, hLeaf / 2, up);
  if (Q.lod !== 0) return;

  // stiles and rails, proud of the panels: a panelled door reads by its
  // shadows, and these are the shadows
  const at = u => off(off(a, Xd, u), Nd, t / 2 + pr / 2);
  const stile = (u, w) => {
    const p = at(u);
    beam(bags.trim, [p[0], yB + 0.004, p[2]], [p[0], yT - 0.004, p[2]],
         w / 2, pr / 2, Nd);
  };
  const rail = (yc, hgt) => {
    const p0 = at(0.004), p1 = at(wLeaf - 0.004);
    beam(bags.trim, [p0[0], yc, p0[2]], [p1[0], yc, p1[2]], pr / 2, hgt / 2, up);
  };
  const lock = yB + hLeaf * (P.doorLight ? 0.52 : 0.44);
  stile(sw / 2, sw); stile(wLeaf - sw / 2, sw);
  rail(yB + sw / 2, sw); rail(yT - sw / 2, sw); rail(lock, sw * 0.85);

  // the light: the small window every Alaskan front door has, so you can see
  // who is on the step in December
  if (P.doorLight) {
    const gy0 = lock + sw * 0.6, gy1 = yT - sw - 0.02;
    if (gy1 > gy0 + 0.12) {
      const g0 = off(off(a, Xd, sw + 0.03), Nd, t / 2 + 0.003);
      const g1 = off(off(a, Xd, wLeaf - sw - 0.03), Nd, t / 2 + 0.003);
      bags.glass.setGlow(litFor(P, W, h));
      face(bags.glass, [[g0[0], gy0, g0[2]], [g1[0], gy0, g1[2]],
                        [g1[0], gy1, g1[2]], [g0[0], gy1, g0[2]]], Nd,
           uvFrame([g0[0], gy0, g0[2]], Xd, up));
      bags.glass.setGlow(0);
    }
  }
  // hardware: three butt hinges and a knob
  for (const f of [0.13, 0.5, 0.87]) {
    const y = yB + hLeaf * f, q = off(a, Xd, 0.012);
    beam(bags.metal, [q[0], y - 0.055, q[2]], [q[0], y + 0.055, q[2]],
         0.020, 0.013, Nd);
  }
  const kp = off(off(a, Xd, wLeaf - 0.10), Nd, t / 2);
  cyl(bags.metal, [kp[0], lock - 0.11, kp[2]], Nd, 0.026, 0.040, 8, true);
  cyl(bags.metal, off([kp[0], lock - 0.11, kp[2]], Nd, 0.040), Nd, 0.018,
      0.038, 8, true);
  // the threshold
  const o0 = W.P(h.s0 - 0.03, h.y0, 1), o1 = W.P(h.s1 + 0.03, h.y0, 1);
  const i0 = W.P(h.s0 - 0.03, h.y0, -1), i1 = W.P(h.s1 + 0.03, h.y0, -1);
  plate(bags.trim, [[o0[0], h.y0 + 0.020, o0[2]], [o1[0], h.y0 + 0.020, o1[2]],
                    [i1[0], h.y0 + 0.020, i1[2]], [i0[0], h.y0 + 0.020, i0[2]]],
        0.032, [0, -1, 0], uvFrame(o0, X, mul(N, -1)));
}

// ---------------------------------------------------------------------------
// THE DORMERS (the user: "windows sticking out of the roof")
// ---------------------------------------------------------------------------
// G229 deferred these with a reason — a dormer needs a VALLEY, and the roof is
// a min-of-planes surface with no notion of one. This is the reason it can be
// done now: on a side facet the main roof is LINEAR IN z, so every line a
// dormer needs is solvable rather than searched for.
//
//   shed   its own shallower plane, rising from the front wall's plate. It
//          meets the main roof at d = dormH / (k - kd) — the depth is not a
//          parameter, it is where the two planes actually cross.
//   gable  a horizontal ridge running up-slope; the two roof planes slope in
//          +/-x only, so the valley is dist(x) = (yRidge - tan*|x-cx| - yf)/k,
//          linear in x, which is what lets the hole in the main roof be cut
//          EXACTLY rather than approximated by its bounding box.
//
// And the hole is cut: `roofFacetHoles` emits the facet as columns with a
// per-column z range removed, top and underside, with a reveal round the
// opening. A dormer sitting ON an unbroken roof is the giveaway of a kit.
function dormerList(P, V, R) {
  const n = Math.round(P.dormers);
  if (!n) return [];
  const out = [];
  // ASKED FOR, AND NOT POSSIBLE. A 10-degree roof cannot carry a shed dormer
  // whose own roof must be shallower still: the crossing would be past the
  // ridge and the honest answer is none, said out loud — the same rule as an
  // opening that will not fit its wall.
  let skipped = 0;
  const sides = Math.round(P.dormSide);      // 0 front, 1 back, 2 both
  for (const f of R.facets) {
    if (!f.eaveTrue) continue;
    const o = eaveOut(f);
    if (Math.abs(o[2]) < 0.9) continue;      // side facets only
    const front = o[2] > 0;
    if (sides === 0 && !front) continue;
    if (sides === 1 && front) continue;
    const sgn = front ? 1 : -1;
    const k = Math.abs(f.q[0][1] - f.q[3][1]) /
              Math.max(1e-6, Math.abs(f.q[0][2] - f.q[3][2]));   // main pitch
    if (k < 0.08) continue;                  // a flat roof has no dormer
    const kd0 = Math.min(k * 0.72, Math.tan(clamp(P.dormPitch, 4, 45) * D2R));
    for (let i = 0; i < n; i++) {
      let kd = kd0;
      const cx = (-V.L / 2) + V.L * (i + 0.5) / n;
      const hw = Math.min(P.dormW, V.L / n - 0.5) / 2;
      if (hw < 0.35) continue;
      const zf = sgn * (V.w / 2 - P.dormSet);
      const yf = R.topAt(cx, zf);
      const kind = Math.round(P.dormKind);
      // IT HAS TO FIT ON THE ROOF. A dormer's depth is not a parameter — it is
      // where its own roof crosses the main one — and at a shallow main pitch
      // that crossing can be PAST THE RIDGE, which drew a fold of roof laid
      // back over itself and a hole into the far side of the house. The wall
      // height is clamped instead, and the count of clamped dormers is
      // published: same rule as an opening that will not fit.
      const avail = Math.abs(zf - f.q[3][2]) * 0.82;
      let dH = P.dormH, clamped = 0, kdUse = kd;
      // THE DORMER'S OWN PITCH IS THE FIRST THING TO GIVE, not its height.
      // A builder facing a shallow main roof lays the dormer's roof flatter;
      // he does not build a 30 cm dormer. The first cut clamped the HEIGHT and
      // produced exactly that — the letterbox slots the user photographed. So:
      // flatten kd until it fits (down to 5 degrees), and only then shorten.
      const FLAT = Math.tan(5 * D2R);
      // A DORMER EXISTS FOR ITS WINDOW (the user: "some dormers have no
      // window"). The first cut sized the dormer, then asked whether a window
      // fitted, and silently built a blind box when it did not. Now the WINDOW
      // sets the floor: the wall must carry a sill, the smallest sash worth
      // drawing, and the head casing under the roof — and if the roof cannot
      // carry that much dormer, there is no dormer.
      const needH = 0.26 + 0.42 + P.trimW * 0.5 + 0.06 +
                    Math.min(0.09, V.roofT * 0.7);
      if (kind === 0) {
        const need = k - dH / Math.max(0.3, avail);
        kdUse = clamp(Math.min(kd, need), FLAT, Math.max(FLAT, k * 0.85));
        const maxH = avail * (k - kdUse);
        if (maxH < needH) { skipped++; continue; }
        if (dH > maxH) { dH = maxH; clamped = 1; }
      } else {
        const need = (avail * k - dH) / Math.max(0.2, hw);
        kdUse = clamp(Math.min(kd, need), FLAT, Math.max(FLAT, kd));
        const maxH = avail * k - hw * kdUse;
        if (maxH < needH) { skipped++; continue; }
        if (dH > maxH) { dH = maxH; clamped = 1; }
      }
      if (dH < needH) { dH = Math.min(needH, kind === 0
        ? avail * (k - kdUse) : avail * k - hw * kdUse); }
      kd = kdUse;
      out.push({ f: f, sgn: sgn, cx: cx, hw: hw, zf: zf, yf: yf, k: k, kd: kd,
                 kind: kind, dH: dH, clamped: clamped });
    }
  }
  out.skipped = skipped;
  return out;
}

// how far up-slope the dormer's own roof runs before it meets the main one,
// as a function of x within the dormer's width (the valley)
function dormerBack(d, x) {
  if (d.kind === 0) return d.dH / Math.max(0.02, d.k - d.kd);
  const yRidge = d.yf + d.dH + d.hw * d.kd;
  return Math.max(0.15, (yRidge - Math.abs(x - d.cx) * d.kd - d.yf) / d.k);
}

// THE FACET, WITH HOLES IN IT. Columns split at the dormers' own x edges (and
// at a gable dormer's ridge, where the valley kinks); each column loses the z
// band the dormer stands in, and the band's far edge is interpolated across
// the column — which is exact, because the valley is linear in x.
function roofFacetHoles(bag, f, V, dorms, P) {
  const q = f.q;
  const xs = [Math.min(q[0][0], q[1][0]), Math.max(q[0][0], q[1][0])];
  const zE = q[0][2], zT = q[3][2];
  const dz = Math.sign(zT - zE);
  const yAt = (x, z) => {                    // the facet's own plane
    const t = (z - zE) / (zT - zE || 1);
    return q[0][1] + (q[3][1] - q[0][1]) * t;
  };
  const cuts = [xs[0], xs[1]];
  for (const d of dorms) {
    cuts.push(clamp(d.cx - d.hw, xs[0], xs[1]), clamp(d.cx + d.hw, xs[0], xs[1]));
    if (d.kind === 1) cuts.push(clamp(d.cx, xs[0], xs[1]));
  }
  cuts.sort((a, b) => a - b);
  const cols = [];
  for (let i = 0; i + 1 < cuts.length; i++)
    if (cuts[i + 1] - cuts[i] > 1e-4) cols.push([cuts[i], cuts[i + 1]]);
  const T = V.roofT;
  // up the SLOPE, not across the plan: a 34-degree roof mapped from above is
  // stretched by 1/cos(34) in one direction and nothing says so
  const slopeV = nrm(sub([q[3][0], q[3][1], q[3][2]], [q[0][0], q[0][1], q[0][2]]));
  const uvSlope = uvFrame(q[0], [1, 0, 0], slopeV);
  const P3 = (x, z) => [x, yAt(x, z), z];
  const B3 = (x, z) => [x, yAt(x, z) - T, z];
  for (const c of cols) {
    const xa = c[0], xb = c[1], xm = (xa + xb) / 2;
    const d = dorms.find(dd => xm > dd.cx - dd.hw && xm < dd.cx + dd.hw);
    // the z bands this column keeps
    const bands = [];
    if (!d) bands.push([zE, zT]);
    else {
      const zNear = d.zf;
      const zFarA = d.zf + dz * dormerBack(d, xa);
      const zFarB = d.zf + dz * dormerBack(d, xb);
      bands.push([zE, zNear]);
      bands.push([zFarA, zT, zFarB]);        // sloped near edge
    }
    for (const b of bands) {
      const cz = v => (dz > 0 ? clamp(v, zE, zT) : clamp(v, zT, zE));
      const z0a = cz(b[0]), z1 = cz(b[1]),
            z0b = cz(b.length > 2 ? b[2] : b[0]);
      if (Math.abs(z1 - z0a) < 1e-4 && Math.abs(z1 - z0b) < 1e-4) continue;
      if ((z1 - z0a) * dz < -1e-4 || (z1 - z0b) * dz < -1e-4) continue;
      face(bag, [P3(xa, z0a), P3(xb, z0b), P3(xb, z1), P3(xa, z1)], [0, 1, 0],
           uvSlope);
      face(bag, [B3(xa, z0a), B3(xa, z1), B3(xb, z1), B3(xb, z0b)], [0, -1, 0],
           uvSlope);
    }
  }
  // the outer boundary: eave, ridge and the two rakes, as before
  const edge = (p0, p1, n) => face(bag, [p0, p1, [p1[0], p1[1] - T, p1[2]],
                                         [p0[0], p0[1] - T, p0[2]]], n,
                                   uvFrame(p0, nrm(sub(p1, p0)), [0, -1, 0]));
  edge(P3(xs[1], zE), P3(xs[0], zE), [0, 0, -dz]);
  edge(P3(xs[0], zT), P3(xs[1], zT), [0, 0, dz]);
  edge(P3(xs[0], zE), P3(xs[0], zT), [-1, 0, 0]);
  edge(P3(xs[1], zT), P3(xs[1], zE), [1, 0, 0]);
  // and the reveal round each opening — the cut edge of the roof itself
  for (const d of dorms) {
    const x0 = clamp(d.cx - d.hw, xs[0], xs[1]);
    const x1 = clamp(d.cx + d.hw, xs[0], xs[1]);
    const zF0 = d.zf + dz * dormerBack(d, x0);
    const zF1 = d.zf + dz * dormerBack(d, x1);
    edge(P3(x0, d.zf), P3(x1, d.zf), [0, 0, dz]);
    edge(P3(x1, zF1), P3(x0, zF0), [0, 0, -dz]);
    edge(P3(x0, zF0), P3(x0, d.zf), [1, 0, 0]);
    edge(P3(x1, d.zf), P3(x1, zF1), [-1, 0, 0]);
    if (d.kind === 1) {                       // the valley kinks at the ridge
      const zm = d.zf + dz * dormerBack(d, d.cx);
      edge(P3(d.cx, zm), P3(x0, zF0), [0, 0, -dz]);
      edge(P3(x1, zF1), P3(d.cx, zm), [0, 0, -dz]);
    }
  }
}

// the dormer itself: front wall (with its window), two cheeks, its own roof
function buildDormer(bags, P, Q, V, R, d) {
  const sgn = d.sgn, cx = d.cx, hw = d.hw, zf = d.zf, yf = d.yf;
  const yTop = yf + d.dH;
  const rt = Math.min(0.09, V.roofT * 0.7);
  const gable = d.kind === 1;
  const yRidge = gable ? yTop + hw * d.kd : yTop;
  const back = x => zf + sgn * -1 * dormerBack(d, x) * (sgn > 0 ? 1 : 1);
  // up-slope is TOWARD the ridge, i.e. z decreasing in magnitude
  const zAt = dist => zf - sgn * dist;
  const t = Math.min(0.12, V.wallT);

  // ---- the front wall, its top following the dormer's own roof -------------
  const A = sgn > 0 ? [cx - hw, zf] : [cx + hw, zf];
  const B = sgn > 0 ? [cx + hw, zf] : [cx - hw, zf];
  const Lw = 2 * hw;
  const topAt = s => {
    const x = A[0] + (B[0] - A[0]) * s / Lw;
    return (gable ? yRidge - Math.abs(x - cx) * d.kd : yTop) - rt;
  };
  const holes = [];
  // THE WINDOW STOPS UNDER THE ROOF, CASING AND ALL (the user: "the angled
  // roof of the dormers goes through the vertical frame of the window"). The
  // head board stands `trimW/2 + 30 mm` above the opening, and on a shed
  // dormer the roof is lowest at the FRONT face — so that, plus the roof's own
  // thickness, is what the opening has to clear.
  const yLo = yf + 0.26;
  const headroom = (gable ? yRidge - hw * d.kd : yTop) - rt
                   - (P.trimW * 0.5 + 0.06) - yLo;
  const winW = Math.min(P.winW, Lw - 0.34 - P.trimW * 2);
  const winH = Math.min(P.winH * 0.85, headroom);
  if (Q.lod === 0 && winW > 0.3 && winH > 0.36)
    holes.push({ s0: Lw / 2 - winW / 2, s1: Lw / 2 + winW / 2,
                 y0: yLo, y1: yLo + winH, kind: 'window' });
  const W = wall(bags.siding, {
    A: A, B: B, y0: yf - 0.05, t: t, topAt: topAt, holes: holes,
    splits: gable ? [Lw / 2] : [], inner: true, capTop: Q.lod === 0,
    capBot: false, endCap: [false, false],
    sub: Q.lod === 0 ? (P.aoRange || 0.55) * 0.85 : 0,
  });
  if (W && Q.lod === 0)
    for (const h of holes) dressOpening(bags, P, Q, W, h, h.y1);
  d.hasWindow = holes.length > 0;

  // ---- THE FLOOR OF THE DORMER --------------------------------------------
  // The hole is real, and without this you look through it into an empty house
  // and out at the inside of the far wall — which is what a cut roof with no
  // attic floor under it actually looks like. The dormer stands on the attic
  // floor, so that is what closes it: the same polygon as the opening, one
  // storey plate down.
  if (Q.lod === 0) {
    const x0 = cx - hw, x1 = cx + hw;
    const yFl = Math.min(V.plateY, yf - 0.12);
    const ring = [[x0, yFl, zf], [x1, yFl, zf],
                  [x1, yFl, zAt(dormerBack(d, x1))]];
    if (gable) ring.push([cx, yFl, zAt(dormerBack(d, cx))]);
    ring.push([x0, yFl, zAt(dormerBack(d, x0))]);
    plate(bags.floor, ring, 0.06, [0, -1, 0], p2 => [p2[0], p2[2]]);
  }

  // ---- the cheeks: bounded below by the MAIN roof, above by the dormer's ---
  for (const s of [-1, 1]) {
    const x = cx + s * hw;
    const yD = gable ? yRidge - hw * d.kd - rt : yTop - rt;
    const kd = gable ? 0 : d.kd;             // a gable dormer's cheek top is level
    // main roof under this cheek: y = yf + k*dist ; cheek top: yD + kd*dist
    const dEnd = Math.max(0.05, (yD - yf) / Math.max(0.02, d.k - kd));
    const ring = [[x, yf - 0.02, zf], [x, yD, zf],
                  [x, yf + d.k * dEnd, zAt(dEnd)]];
    plate(bags.siding, ring, t, [s > 0 ? -1 : 1, 0, 0],
          uvFrame(ring[0], [0, 0, -sgn], [0, 1, 0]));
  }

  // ---- its own roof --------------------------------------------------------
  const fo = 0.10;                            // a small overhang at the front
  if (gable) {
    for (const s of [-1, 1]) {
      const xe = cx + s * (hw + fo);
      const yE = yRidge - (hw + fo) * d.kd;
      const dEave = Math.max(0.05, (yE - yf) / d.k);
      const dRid = Math.max(0.05, (yRidge - yf) / d.k);
      const ring = [[xe, yE, zAt(-fo)], [cx, yRidge, zAt(-fo)],
                    [cx, yRidge, zAt(dRid)], [xe, yE, zAt(dEave)]];
      plate(bags.roof, ring, rt, [0, -1, 0],
            uvFrame(ring[0], nrm(sub(ring[1], ring[0])),
                    nrm(sub(ring[3], ring[0]))));
      // front edge and outer rake are free; the ridge and the valley are not
      if (Q.lod === 0)
        roofRim(bags.trim, ring, [true, false, false, true], rt + 0.075, 0.024);
    }
  } else {
    const dEnd = Math.max(0.10, d.dH / Math.max(0.02, d.k - d.kd));
    const yBack = yTop + d.kd * dEnd;
    const ring = [[cx - hw - fo, yTop, zAt(-fo)], [cx + hw + fo, yTop, zAt(-fo)],
                  [cx + hw + fo, yBack, zAt(dEnd)], [cx - hw - fo, yBack,
                                                     zAt(dEnd)]];
    plate(bags.roof, ring, rt, [0, -1, 0],
          uvFrame(ring[0], [1, 0, 0], nrm(sub(ring[3], ring[0]))));
    // front and both cheeks are free; the back dies into the main roof
    if (Q.lod === 0)
      roofRim(bags.trim, ring, [true, true, false, true], rt + 0.075, 0.024);
  }
}

// ---------------------------------------------------------------------------
// THE CUPOLA (the user: "maybe some octagonal pieces")
// ---------------------------------------------------------------------------
// The belfry off the church in the photograph: an octagonal drum straddling
// the ridge, louvred on every face, with a cornice, a spire and a finial. Its
// BASE RING READS THE ROOF — each vertex takes its own y off the roof surface
// under it — so it sits down on the slope instead of hovering over the eaves
// with daylight under two of its eight sides.
function buildCupola(bags, P, Q, V, R) {
  if (!P.cupola) return null;
  const n = Math.max(4, Math.round(P.cupSides));
  const r = P.cupR;
  const cx = clamp(P.cupXF * (V.L / 2 - r * 1.6), -V.L / 2 + r, V.L / 2 - r);
  const rot = Math.PI / n;                    // a flat facing front, not a corner
  const yDeck = R.ridgeY + 0.06;
  // the curb: down onto the roof, up to just over the ridge
  const bot = K.ringN(cx, 0, r * 1.22, n, rot, (x, z) => R.topAt(x, z) - 0.06);
  const curb = K.ringN(cx, 0, r * 1.22, n, rot, yDeck);
  K.prismRings(bags.siding, bot, curb, false, false);
  const sillTop = K.ringN(cx, 0, r * 1.10, n, rot, yDeck + 0.10);
  K.prismRings(bags.trim, curb, sillTop, false, false);
  // the drum
  const body = K.ringN(cx, 0, r, n, rot, yDeck + 0.10);
  const bodyTop = K.ringN(cx, 0, r, n, rot, yDeck + 0.10 + P.cupH);
  K.prismRings(bags.siding, body, bodyTop, false, false);
  if (Q.lod === 0) {
    // corner posts and louvres — the openings a bell has to be heard through
    for (let i = 0; i < n; i++) {
      beam(bags.trim, body[i], bodyTop[i], 0.035, 0.035, [0, 1, 0]);
      const j = (i + 1) % n;
      const nSl = 4;
      for (let s = 1; s <= nSl; s++) {
        const y = body[i][1] + P.cupH * (s / (nSl + 1));
        const a = [body[i][0], y, body[i][2]], b = [body[j][0], y, body[j][2]];
        const mid = K.lerp3(a, b, 0.5);
        const outN = nrm([mid[0] - cx, 0, mid[2]]);
        beam(bags.trim, off(a, outN, 0.012), off(b, outN, 0.012),
             0.012, 0.026, [0, 1, 0]);
      }
    }
  }
  // cornice, spire, finial
  const corn0 = K.ringN(cx, 0, r * 1.16, n, rot, bodyTop[0][1]);
  const corn1 = K.ringN(cx, 0, r * 1.16, n, rot, bodyTop[0][1] + 0.09);
  K.prismRings(bags.trim, corn0, corn1, false, true);
  const eave = K.ringN(cx, 0, r * 1.16, n, rot, bodyTop[0][1] + 0.09);
  const apex = [cx, bodyTop[0][1] + 0.09 + P.cupSpire, 0];
  K.apexTo(bags.roof, eave, apex);
  // THE FINIAL AND THE CROSS SURVIVE INTO lod 1. They are two hundred grams of
  // metal and eighteen triangles, and they are also the top 0.9 m of the
  // building's outline — leave them out of the far mesh and the church is a
  // different shape from a kilometre away, which the LOD parity rule notices
  // before anybody's eye does.
  const seg = Q.lod === 0 ? 8 : 5;
  cyl(bags.metal, apex, [0, 1, 0], 0.028, 0.34, seg, true);
  const bl = [apex[0], apex[1] + 0.34, apex[2]];
  K.prismRings(bags.metal, K.ringN(cx, 0, 0.075, seg, 0, bl[1]),
               K.ringN(cx, 0, 0.075, seg, 0, bl[1] + 0.10), false, false);
  K.apexTo(bags.metal, K.ringN(cx, 0, 0.075, seg, 0, bl[1] + 0.10),
           [cx, bl[1] + 0.22, 0]);
  let top = bl[1] + 0.22;
  if (P.cupCross) {                            // the church in the photograph
    const cy = bl[1] + 0.30;
    beam(bags.metal, [cx, cy, 0], [cx, cy + 0.55, 0], 0.020, 0.020, [1, 0, 0]);
    beam(bags.metal, [cx - 0.17, cy + 0.38, 0], [cx + 0.17, cy + 0.38, 0],
         0.020, 0.020, [0, 0, 1]);
    top = cy + 0.55;
  }
  return { x: cx, r: r, top: top, spire: apex[1], sides: n };
}

// ---------------------------------------------------------------------------
// THE STANCE — what holds it above the ground
// ---------------------------------------------------------------------------
function buildStance(bags, P, Q, V, plan, g) {
  const marks = { posts: 0, freeMax: 0, clearMin: Infinity, inWater: 0 };
  const sz = P.postSz / 2, floorBase = V.floorY - 0.10;
  // the floor platform: a rim beam round the plan and (lod 0) joists across
  const half = V.wallT / 2;
  const beamH = Math.min(0.30, Math.max(0.14, V.floorY * 0.28));
  const yTop = floorBase, yBot = floorBase - beamH;
  for (let i = 0; i < plan.length; i++) {
    const A = plan[i], B = plan[(i + 1) % plan.length];
    beam(bags.post, [A[0], (yTop + yBot) / 2, A[1]],
         [B[0], (yTop + yBot) / 2, B[1]], half, beamH / 2, [0, 1, 0], 0,
         bevUV(P, Q, jog(A[0], A[1], 14)));
  }
  if (Q.lod === 0 && P.joists) {
    const x0 = plan[0][0], x1 = plan[1][0];
    const z0 = Math.min(plan[0][1], plan[2][1]) + half;
    const z1 = Math.max(plan[0][1], plan[2][1]) - half;
    const n = Math.max(2, Math.round(Math.abs(x1 - x0) / 0.6));
    for (let i = 1; i < n; i++) {
      const x = Math.min(x0, x1) + Math.abs(x1 - x0) * i / n;
      beam(bags.post, [x, (yTop + yBot) / 2 - 0.01, z0],
           [x, (yTop + yBot) / 2 - 0.01, z1], 0.035, beamH / 2 - 0.02,
           [0, 1, 0]);
    }
  }
  // the floor deck itself, so you cannot see up into an empty box
  const fx0 = Math.min(plan[0][0], plan[1][0]), fx1 = Math.max(plan[0][0], plan[1][0]);
  const fz0 = Math.min(plan[0][1], plan[2][1]), fz1 = Math.max(plan[0][1], plan[2][1]);
  boxAB(bags.floor, [fx0, yTop, fz0], [fx1, yTop + 0.05, fz1]);
  if (P.storeys > 1 && Q.lod === 0)
    for (let s = 1; s < P.storeys; s++)
      boxAB(bags.floor, [fx0, V.floorY + s * P.floorH - 0.05, fz0],
            [fx1, V.floorY + s * P.floorH, fz1]);

  // SKIDS: what a shed sits on. Two sill beams under the long walls, blocked
  // up off the wet with whatever was to hand. No posts, no crawl space — a
  // storage shed is not a house and must not be built like one.
  if (Math.round(P.stance) === 4) {
    const zA = plan[0][1] - half + 0.10, zB = plan[2][1] + half - 0.10;
    for (const z of [zA, zB]) {
      const yA = g(fx0, z), yB2 = g(fx1, z);
      const y = Math.max(yA, yB2) + 0.10;
      beam(bags.post, [fx0 - 0.10, y, z], [fx1 + 0.10, y, z], 0.09, 0.09,
           [0, 1, 0]);
      const n = Math.max(2, Math.round((fx1 - fx0) / 1.6));
      for (let i = 0; i <= n; i++) {
        const x = fx0 + (fx1 - fx0) * i / n;
        const gy = g(x, z);
        if (y - 0.09 - gy < 0.02) continue;
        boxAB(bags.stone, [x - 0.14, gy - 0.05, z - 0.14],
              [x + 0.14, y - 0.085, z + 0.14]);
      }
      marks.clearMin = Math.min(marks.clearMin, y - 0.09 - Math.max(yA, yB2));
    }
    marks.clearMin = Math.max(0, marks.clearMin);
    return marks;
  }

  if (P.stance === 0) {                        // SLAB: a plinth, no posts
    const gLo = Math.min(g(fx0, fz0), g(fx1, fz0), g(fx0, fz1), g(fx1, fz1));
    boxAB(bags.stone, [fx0 + 0.06, gLo - 0.35, fz0 + 0.06],
          [fx1 - 0.06, yBot, fz1 - 0.06]);
    marks.clearMin = 0;
    return marks;
  }
  // POSTS. One line of them under each wall, at the spacing asked for, each
  // cut to the ground under its own foot — which is the entire difference
  // between a house on a beach and a house on a table.
  const feet = [];
  for (let i = 0; i < plan.length; i++) {
    const A = plan[i], B = plan[(i + 1) % plan.length];
    const L = Math.hypot(B[0] - A[0], B[1] - A[1]);
    const n = Math.max(1, Math.round(L / P.postSpc));
    for (let j = 0; j <= n; j++) {
      if (i > 0 && j === 0) continue;           // the corner is already posted
      const u = j / n;
      feet.push([A[0] + (B[0] - A[0]) * u, A[1] + (B[1] - A[1]) * u]);
    }
  }
  // PILES ARE NOT POSTS (the user: "more complex pillar structure for ability
  // to build partly in the water"). A post stands on a pad on dry ground. A
  // pile is DRIVEN: it is round, it goes down through the beach into whatever
  // holds it, it takes no footing, and it never stands alone — the outboard
  // ones are BATTERED (raked outward) and tied back to the building's line
  // with a cap and a brace, which is what stops a bent racking when the
  // building is half over the water. Creek Street, in one paragraph.
  const piles = Math.round(P.stance) === 3;
  const wet = P.water ? P.waterY : -1e9;
  for (const f of feet) {
    const gy = g(f[0], f[1]);
    const padT = (Q.lod === 0 && !piles) ? P.padSz * 0.30 : 0;
    if (Q.lod === 0 && !piles)
      boxAB(bags.stone, [f[0] - P.padSz / 2, gy - 0.10, f[1] - P.padSz / 2],
            [f[0] + P.padSz / 2, gy + padT, f[1] + P.padSz / 2]);
    if (piles) {
      const r = P.postSz * 0.62;
      // driven in: it starts below the mud line, not on it
      // a pile at eighty metres is a stick: four sides, and no caps on the
      // end that is buried and the end that is under the floor
      cyl(bags.post, [f[0], gy - 0.35, f[1]], [0, 1, 0], r,
          (yBot + 0.02) - (gy - 0.35), Q.lod === 0 ? 9 : 4, Q.lod === 0,
          timberUV(f[0], f[1], 1));
      if (P.pileBent) {
        // The battered outboard pile of the bent, and the cap it carries. The
        // RAKED LEG IS THE SILHOUETTE of a building standing in the water, so
        // it survives into lod 1 (at four sides and without its cap) — the
        // gate holds the two meshes to the same outline and this is one of the
        // few details that earns its place out there.
        const out = [Math.sign(f[0]) * (Math.abs(f[0]) > Math.abs(f[1]) ? 1 : 0),
                     0, Math.sign(f[1]) * (Math.abs(f[1]) >= Math.abs(f[0]) ? 1 : 0)];
        const bx = f[0] + out[0] * P.pileBatter, bz = f[1] + out[2] * P.pileBatter;
        const bgy = g(bx, bz);
        cyl(bags.post, [bx, bgy - 0.35, bz],
            nrm([f[0] - bx, (yBot - 0.10) - (bgy - 0.35), f[1] - bz]), r * 0.85,
            len([f[0] - bx, (yBot - 0.10) - (bgy - 0.35), f[1] - bz]),
            Q.lod === 0 ? 9 : 4, true, timberUV(bx, bz, 2));
        if (Q.lod === 0)
          beam(bags.post, [bx, yBot - 0.06, bz],
               [f[0] - out[0] * 0.12, yBot - 0.06, f[1] - out[2] * 0.12],
               0.06, 0.07, [0, 1, 0]);
      }
    } else {
      beam(bags.post, [f[0], gy + padT, f[1]], [f[0], yBot + 0.02, f[1]],
           sz, sz, [0, 0, 1], 0,
           { uv: jog(f[0], f[1], 7), bevel: Q.lod === 0 ? P.bevel : 0 });
    }
    marks.posts++;
    marks.freeMax = Math.max(marks.freeMax, yBot - gy);
    marks.clearMin = Math.min(marks.clearMin, yBot - gy);
    if (gy < wet) marks.inWater++;
  }
  // X-bracing along every wall once the legs are long — on dry ground the two
  // ends are enough (they carry the racking); over water, everything is long
  if (Q.lod === 0 && piles && P.brace) {
    const byWall = {};
    for (const f of feet) {
      const kx = Math.abs(Math.abs(f[0]) - V.L / 2) < 1e-3 ? 'x' + f[0].toFixed(2)
        : 'z' + f[1].toFixed(2);
      (byWall[kx] = byWall[kx] || []).push(f);
    }
    for (const kx in byWall) {
      const col = byWall[kx].slice().sort((a, b) =>
        (a[0] - b[0]) || (a[1] - b[1]));
      for (let i = 0; i + 1 < col.length; i++) {
        const a = col[i], b = col[i + 1];
        const ga = g(a[0], a[1]), gb = g(b[0], b[1]);
        const free = yBot - Math.max(ga, gb);
        if (free < 1.4) continue;
        const y0 = Math.max(ga, gb) + free * 0.12;
        beam(bags.post, [a[0], y0, a[1]], [b[0], yBot - 0.14, b[1]],
             0.042, 0.062, [0, 1, 0]);
        beam(bags.post, [b[0], y0, b[1]], [a[0], yBot - 0.14, a[1]],
             0.042, 0.062, [0, 1, 0]);
      }
    }
  }
  // cross braces on the two ends, which is where the racking load is
  if (Q.lod === 0 && P.brace && Math.round(P.stance) === 2) {
    for (const sx of [-1, 1]) {
      const xEnd = sx * (V.L / 2);
      const col = feet.filter(f => Math.abs(f[0] - xEnd) < 1e-3)
                      .sort((a, b) => a[1] - b[1]);
      for (let i = 0; i + 1 < col.length; i++) {
        const a = col[i], b = col[i + 1];
        const ga = g(a[0], a[1]), gb = g(b[0], b[1]);
        if (yBot - Math.max(ga, gb) < 0.6) continue;
        beam(bags.post, [a[0], ga + 0.15, a[1]], [b[0], yBot - 0.10, b[1]],
             0.035, 0.055, [0, 1, 0]);
        beam(bags.post, [b[0], gb + 0.15, b[1]], [a[0], yBot - 0.10, a[1]],
             0.035, 0.055, [0, 1, 0]);
      }
    }
  }
  // the skirt: what actually keeps the wind (and the porcupines) out
  if (P.skirt > 0) {
    // WHAT THE SKIRT IS MADE OF. A lattice is boards (veneer), a boarded skirt
    // is cladding (planks), and a solid base is CONCRETE — the user found one
    // wearing a veneer, which is a wall panel where a foundation should be.
    const kind = Math.round(P.skirt);
    const bag = kind === 1 ? bags.deck : (kind === 2 ? bags.siding : bags.stone);
    const th = kind === 1 ? 0.03 : (kind === 3 ? 0.14 : 0.05);
    for (let i = 0; i < plan.length; i++) {
      const A = plan[i], B = plan[(i + 1) % plan.length];
      const ga = g(A[0], A[1]), gb = g(B[0], B[1]);
      const mid = [(A[0] + B[0]) / 2, (A[1] + B[1]) / 2];
      const dir = nrm([B[0] - A[0], 0, B[1] - A[1]]);
      const nO = [-dir[2], 0, dir[0]];
      const a3 = [A[0] + nO[0] * (half - th), 0, A[1] + nO[2] * (half - th)];
      const b3 = [B[0] + nO[0] * (half - th), 0, B[1] + nO[2] * (half - th)];
      // one panel per wall, following the ground at its two ends
      const dropTo = kind === 3 ? Math.min(ga, gb) - 0.25 : null;
      const ring = [[a3[0], dropTo === null ? ga : dropTo, a3[2]],
                    [b3[0], dropTo === null ? gb : dropTo, b3[2]],
                    [b3[0], yBot, b3[2]], [a3[0], yBot, a3[2]]];
      plate(bag, ring, th, mul(nO, -1), uvFrame(ring[0], dir, [0, 1, 0]),
            { sub: Q.lod === 0 ? 0.9 : 0 });
    }
    marks.clearMin = 0;
  }
  return marks;
}

// ---------------------------------------------------------------------------
// THE DECK, THE RAIL AND THE STAIR
// ---------------------------------------------------------------------------
function buildDeck(bags, P, Q, V, R, g) {
  const out = { area: 0, stair: null, railH: 0 };
  if (!P.porch) return out;
  const half = V.wallT / 2;
  const zIn = V.w / 2 - half;                    // the deck starts at the wall
  const zOut = zIn + P.porchD;
  const dl = Math.min(V.L * P.porchLenF, V.L + 2 * P.porchD);
  const cx = P.porchOff * V.L / 2;
  const x0 = cx - dl / 2, x1 = cx + dl / 2;
  const yTop = V.floorY - 0.02;
  const rim = 0.20;
  out.area = dl * P.porchD;

  // structure: rim beams all round, joists across (lod 0), then the boards
  const rimY = yTop - rim / 2 - 0.02;
  beam(bags.post, [x0, rimY, zOut], [x1, rimY, zOut], 0.05, rim / 2, [0, 1, 0]);
  beam(bags.deck, [x0, rimY, zIn], [x0, rimY, zOut], 0.05, rim / 2, [0, 1, 0]);
  beam(bags.deck, [x1, rimY, zIn], [x1, rimY, zOut], 0.05, rim / 2, [0, 1, 0]);
  if (Q.lod === 0) {
    const n = Math.max(2, Math.round(dl / 0.55));
    for (let i = 1; i < n; i++) {
      const x = x0 + dl * i / n;
      beam(bags.post, [x, rimY, zIn], [x, rimY, zOut], 0.035, rim / 2 - 0.02,
           [0, 1, 0]);
    }
  }
  if (Q.lod === 0) {
    // boards run ACROSS the deck (the way you walk on to it), with a 8 mm gap
    const bw = P.deckBoard, gap = 0.008;
    const n = Math.max(1, Math.floor((zOut - zIn) / (bw + gap)));
    // EVERY BOARD IS A DIFFERENT BOARD (the user: "the planks are too similar,
    // you may want to shift their UV coordinates for variation"). One offset
    // per board, deterministic in its index, moves it along the scan — the
    // knots and the grain stop lining up across the deck for free.
    for (let i = 0; i < n; i++) {
      const z = zIn + i * (bw + gap);
      const j = (i * 2654435761) >>> 0;
      boxAB(bags.deck, [x0, yTop - 0.035, z], [x1, yTop, z + bw], null,
            [(j % 977) / 977 * 3.1, (j % 383) / 383 * 1.7]);
    }
  } else {
    boxAB(bags.deck, [x0, yTop - 0.05, zIn], [x1, yTop, zOut]);
  }
  // posts under the outer rim
  const n = Math.max(1, Math.round(dl / P.postSpc));
  for (let i = 0; i <= n; i++) {
    const x = x0 + dl * i / n;
    const gy = g(x, zOut);
    if (Q.lod === 0 && Math.round(P.stance) !== 3)
      boxAB(bags.stone, [x - P.padSz / 2, gy - 0.10, zOut - P.padSz / 2],
            [x + P.padSz / 2, gy + P.padSz * 0.25, zOut + P.padSz / 2]);
    if (Math.round(P.stance) === 3)
      cyl(bags.post, [x, gy - 0.35, zOut], [0, 1, 0], P.postSz * 0.62,
          rimY - (gy - 0.35), Q.lod === 0 ? 9 : 5, true,
          timberUV(x, zOut, 3));
    else
      beam(bags.post, [x, gy + (Q.lod === 0 ? P.padSz * 0.25 : 0), zOut],
           [x, rimY, zOut], P.postSz / 2, P.postSz / 2, [0, 0, 1], 0,
           { uv: jog(x, zOut, 8), bevel: Q.lod === 0 ? P.bevel : 0 });
  }

  // ---- the stair: cut to the ground it lands on, not to a fixed run --------
  let stairGap = null;
  if (P.stairs) {
    const sx = clamp(P.door ? (doorPosOf(P, V) - 0.5) * V.L : cx,
                     x0 + P.stairW / 2 + 0.1, x1 - P.stairW / 2 - 0.1);
    // WHERE THE STAIR LANDS. On dry ground it lands on the ground; over water
    // it lands on a LANDING — a small jetty on its own piles, a hand's breadth
    // over the tide, with a pair of mooring posts (the user: "If stairs are
    // going into the water, you may want to do a little 'embarcadère'
    // structure to have boats"). A flight of steps disappearing into the sea
    // is the one thing a beach house never has.
    const wet = P.water ? P.waterY : -1e9;
    const landY = P.water ? wet + 0.38 : null;
    const surf = (xx, zz) => {
      const gAt = g(xx, zz);
      return (landY !== null && gAt < wet) ? landY : gAt;
    };
    const sp = stairPlan(P, { x: sx, w: P.stairW, zTop: zOut, yTop: yTop,
                              dir: 1 }, surf);
    const zFoot = sp.footZ, run = P.stairRun, n = sp.n;
    const gRaw = g(sp.footX, zFoot);
    const onWater = landY !== null && gRaw < wet;
    const gy = onWater ? landY : gRaw;
    out.jetty = onWater ? { x: sp.footX, z: zFoot, y: landY } : null;
    let jetty = out.jetty;
    if (onWater) {
      // the landing itself: deck boards on four piles, and two posts to tie to
      const jw = Math.max(1.6, P.stairW + 0.9), jd = 1.5;
      const jz0 = zFoot - (sp.lands.length ? jd / 2 : 0.25), jz1 = jz0 + jd;
      const jx0 = sp.footX - jw / 2, jx1 = sp.footX + jw / 2;
      // the pier (G252) starts where the jetty ends, so the jetty says where
      jetty.z0 = jz0; jetty.z1 = jz1; jetty.w = jw;
      const rimJ = landY - 0.10;
      for (const zz of [jz0 + 0.12, jz1 - 0.12])
        beam(bags.post, [jx0, rimJ, zz], [jx1, rimJ, zz], 0.05, 0.09,
             [0, 1, 0]);
      if (Q.lod === 0) {
        const bw = P.deckBoard, gp = 0.010;
        const nb = Math.max(1, Math.floor(jd / (bw + gp)));
        for (let i = 0; i < nb; i++) {
          const z = jz0 + i * (bw + gp);
          const j2 = (i * 40503) >>> 0;
          boxAB(bags.deck, [jx0, landY - 0.035, z], [jx1, landY, z + bw], null,
                [(j2 % 811) / 811 * 2.7, (j2 % 331) / 331 * 1.3]);
        }
      } else boxAB(bags.deck, [jx0, landY - 0.05, jz0], [jx1, landY, jz1]);
      for (const zz of [jz0 + 0.15, jz1 - 0.15])
        for (const xx of [jx0 + 0.15, jx1 - 0.15]) {  // eslint-disable-line
          const sea = g(xx, zz);
          cyl(bags.post, [xx, sea - 0.4, zz], [0, 1, 0], P.postSz * 0.55,
              rimJ - (sea - 0.4), Q.lod === 0 ? 8 : 4, Q.lod === 0,
              timberUV(xx, zz, 4));
        }
      if (Q.lod === 0)                    // two bollards, leaning as they do
        for (const xx of [jx0 + 0.10, jx1 - 0.10]) {
          const sea = g(xx, jz1 - 0.10);
          cyl(bags.post, [xx, sea - 0.4, jz1 - 0.10],
              nrm([xx > sp.footX ? 0.06 : -0.06, 1, 0.04]), P.postSz * 0.5,
              (landY + 0.62) - (sea - 0.4), 8, true, timberUV(xx, jz1, 5));
        }
    }
    out.stair = { n: n, rise: sp.rise, run: run, w: P.stairW, x: sx,
                  z0: zOut, z1: zFoot, y0: gy, y1: yTop, turns: sp.lands.length };
    stairGap = [sx - P.stairW / 2 - 0.06, sx + P.stairW / 2 + 0.06];
    buildSteps(bags, P, Q, sp, g);
  }

  // ---- the rail ------------------------------------------------------------
  if (P.railStyle > 0) {
    out.railH = P.railH;
    const runs = [];
    // outer edge, split round the stair; then the two returns
    if (stairGap) {
      runs.push([[x0, zOut], [Math.max(x0, stairGap[0]), zOut]]);
      runs.push([[Math.min(x1, stairGap[1]), zOut], [x1, zOut]]);
    } else runs.push([[x0, zOut], [x1, zOut]]);
    runs.push([[x0, zIn], [x0, zOut]]);
    runs.push([[x1, zIn], [x1, zOut]]);
    for (const r of runs) {
      const a = r[0], b = r[1];
      const L = Math.hypot(b[0] - a[0], b[1] - a[1]);
      if (L < 0.25) continue;
      const nP = Math.max(1, Math.round(L / (Q.lod === 0 ? 1.6 : 2.6)));
      for (let i = 0; i <= nP; i++) {
        const u = i / nP;
        const x = a[0] + (b[0] - a[0]) * u, z = a[1] + (b[1] - a[1]) * u;
        beam(bags.post, [x, yTop - 0.16, z], [x, yTop + P.railH, z],
             0.045, 0.045, [0, 0, 1], 0,
             { uv: jog(x, z, 10), bevel: Q.lod === 0 ? P.bevel : 0 });
      }
      const rail = (y, hw, ht) => beam(bags.deck,
        [a[0], y, a[1]], [b[0], y, b[1]], hw, ht, [0, 1, 0], 0, BEV(P, Q));
      rail(yTop + P.railH, 0.035, 0.028);                 // top rail (cap)
      if (Q.lod === 0) {
        if (P.railStyle === 1) {
          rail(yTop + 0.10, 0.025, 0.022);                // bottom rail
          const nb = Math.max(1, Math.round(L / P.balSpc));
          for (let i = 1; i < nb; i++) {
            const u = i / nb;
            const x = a[0] + (b[0] - a[0]) * u, z = a[1] + (b[1] - a[1]) * u;
            beam(bags.deck, [x, yTop + 0.10, z], [x, yTop + P.railH, z],
                 0.020, 0.020, [0, 0, 1], 0, BEV(P, Q));
          }
        } else if (P.railStyle === 2) {
          const nr = 4;
          for (let i = 0; i < nr; i++)
            rail(yTop + 0.12 + (P.railH - 0.20) * i / (nr - 1), 0.016, 0.012);
        } else {
          const dir = nrm([b[0] - a[0], 0, b[1] - a[1]]);
          const nO = [-dir[2], 0, dir[0]];
          const ring = [[a[0], yTop, a[1]], [b[0], yTop, b[1]],
                        [b[0], yTop + P.railH - 0.04, b[1]],
                        [a[0], yTop + P.railH - 0.04, a[1]]];
          plate(bags.siding, ring, 0.035, nO, uvFrame(ring[0], dir, [0, 1, 0]));
        }
      } else if (P.railStyle !== 0) {
        rail(yTop + 0.45, 0.025, 0.022);
      }
    }
  }

  // ---- the porch roof ------------------------------------------------------
  if (P.porchRoof > 0) {
    const kp = Math.tan(14 * D2R);
    // ONE PLAN, shared with the opening layout: `porchRoofPlan` decided where
    // this lands before a single window was placed
    const PR = porchRoofPlan(P, V);
    const isCanopy = PR.canopy;
    const yWall = PR.yWall, cW = PR.cW, cX = PR.cX, depth = PR.depth;
    const zEdge = zIn + depth;
    const ring = [[cX - cW / 2, yWall, zIn - 0.10],
                  [cX + cW / 2, yWall, zIn - 0.10],
                  [cX + cW / 2, yWall - kp * (depth + 0.1), zEdge],
                  [cX - cW / 2, yWall - kp * (depth + 0.1), zEdge]];
    plate(bags.roof, ring, 0.09, [0, -1, 0],
          uvFrame(ring[0], [1, 0, 0], nrm(sub(ring[3], ring[0]))),
          { sub: Q.lod === 0 ? 1.0 : 0 });
    // three free edges: it dies into the wall along the fourth
    if (Q.lod === 0)
      roofRim(bags.trim, ring, [false, true, true, true], 0.09 + 0.075, 0.026);
    if (Q.lod === 0) {
      // the two knee braces that carry a canopy, or posts to the deck
      if (isCanopy) {
        for (const s of [-1, 1]) {
          const px = cX + s * (cW / 2 - 0.12);
          beam(bags.post, [px, yWall - 0.85, zIn - 0.02],
               [px, yWall - kp * depth - 0.06, zEdge - 0.12], 0.035, 0.045,
               [1, 0, 0]);
        }
      } else {
        for (const s of [-1, 1]) {
          const px = cX + s * (cW / 2 - 0.15);
          beam(bags.post, [px, yTop, zEdge - 0.12],
               [px, yWall - kp * depth - 0.05, zEdge - 0.12],
               0.055, 0.055, [0, 0, 1]);
        }
      }
    }
  }
  return out;
}

// WHERE THE BACK DOOR GOES, and it is not a free choice: the lean-to stands on
// the back wall, and a door inside its span opens into a shed with a stoop
// built through it (the user: "be coordinated with the other features at the
// back, so it does not go through a back shed"). The door slides clear of the
// lean-to if there is room on either side; if the lean-to covers the whole
// wall the stoop simply is not built.
function leanSpan(P, V) {
  if (!P.lean) return null;
  const dl = V.L * P.leanLF, cx = P.leanOff * V.L / 2;
  return [cx - dl / 2 - 0.35, cx + dl / 2 + 0.35];
}
function leanCovers(P, V, x) {
  const sp = leanSpan(P, V);
  return !!sp && x > sp[0] && x < sp[1];
}
function backDoorX(P, V) {
  let x = (clamp(1 - P.backDoorPos, 0.12, 0.88) - 0.5) * V.L;
  const sp = leanSpan(P, V);
  if (sp && x > sp[0] && x < sp[1]) {
    const m = P.doorW / 2 + 0.4;
    const left = sp[0] - m, right = sp[1] + m;
    const okL = left > -V.L / 2 + m, okR = right < V.L / 2 - m;
    if (okL && (!okR || Math.abs(left - x) < Math.abs(right - x))) x = left;
    else if (okR) x = right;
  }
  return clamp(x, -V.L / 2 + P.doorW / 2 + 0.35, V.L / 2 - P.doorW / 2 - 0.35);
}

// A FLIGHT OF STEPS — AND A TURN IF IT IS A LONG ONE (the user: "when the
// stairs are too long, do a 90° bend in the stairs, with a little 'palier'";
// and of the back one, "The smaller stairs at the back still need a full
// structure").
//
// A house on piles over a falling beach can be three metres up, and three
// metres in one straight run is sixteen treads and four and a half metres of
// stair sticking out into the water — a fire escape, not a porch. Past eight
// treads the flight is planned as TWO, with a landing between them and a
// quarter turn on it. The landing is a real platform: rim beams, boards, and
// its own legs cut to the ground under each one, because it carries what the
// deck carries.
//
// THE PLAN IS SEPARATE FROM THE DRAWING for one reason: when a flight turns,
// THE FOOT MOVES — and the caller has to know where it ended up before
// anything is drawn, because that is where the jetty goes if it landed in the
// water. `surf` is the height the stair may land on: the ground, or the tide
// deck over it.
// THIRTEEN TREADS, not eight. Two and a half metres of rise in one flight is
// ordinary — every reference photograph of a porch has it — and the number is
// measured on the STRAIGHT solution, which is already inflated on a slope
// because the foot walks downhill away from the deck. At eight, an ordinary
// shore cabin bent its porch stair, which looks fussy and is not what was
// asked for. The bend is for the flight that is genuinely too long to be one:
// a house on piles over a falling beach, where it is twenty-seven.
const STAIR_MAX = 13;
function stairPlan(P, o, surf) {
  const dir = o.dir === undefined ? 1 : o.dir;          // +1 = +z, -1 = -z
  const run = P.stairRun, w = o.w, x = o.x;
  const zTop = o.zTop, yTop = o.yTop;
  let n = 1, yFoot = yTop, zFoot = zTop;
  for (let it = 0; it < 10; it++) {                     // the straight answer
    yFoot = surf(x, zFoot);
    n = Math.max(1, Math.round((yTop - yFoot) / P.stairRise));
    zFoot = zTop + dir * n * run;
  }
  if (n <= STAIR_MAX || o.turn === 0)
    return { n: n, rise: (yTop - yFoot) / n, w: w, lands: [],
             flights: [{ x: x, z: zTop, ax: [0, dir], n: n, yTop: yTop }],
             footX: x, footZ: zFoot, footY: yFoot };
  // ACROSS THE SLOPE, AND BACK AGAIN. The first turn is the one that pays:
  // walking on down the fall line, the ground runs away under you and every
  // tread you add buys less than a tread of height (twelve degrees of beach
  // against a stair's thirty-two), so the straight flight off a three-metre
  // deck was thirty-five treads and fifteen metres of z. Turn across the
  // contour and the ground stops falling: the rise is fixed at what it is
  // under the landing, and the stair only has to be long enough for it.
  // After that every flight is capped and the stair SWITCHES BACK, each
  // landing a half-turn and one stair-width further out — which is what a
  // hillside stair is, and why it is compact enough to stand beside a house.
  const sgn = o.turn || (x >= 0 ? 1 : -1);
  const nA = Math.min(STAIR_MAX, Math.max(2, Math.round(n / 2)));
  const zL = zTop + dir * (nA * run + w / 2);
  let nB = Math.max(1, n - nA), rise = (yTop - yFoot) / n, out = null;
  for (let it = 0; it < 10; it++) {
    const parts = Math.max(1, Math.ceil(nB / STAIR_MAX));
    const each = Math.ceil(nB / parts);
    const yMid = yTop - nA * rise;
    const flights = [{ x: x, z: zTop, ax: [0, dir], n: nA, yTop: yTop }];
    // `open` is the edges a FLIGHT attaches to, as outward normals: the
    // incoming flight enters across -ax, the outgoing one leaves across +ax.
    // Everything else is a drop, and gets a rail.
    const lands = [{ x: x, z: zL, y: yMid, w: w, d: w,
                     open: [[0, -dir], [sgn, 0]] }];      // the quarter turn
    let px = x + sgn * w / 2, pz = zL, py = yMid, s2 = sgn, left = nB;
    for (let k = 0; k < parts && left > 0; k++) {
      const nk = Math.min(each, left);
      left -= nk;
      flights.push({ x: px, z: pz, ax: [s2, 0], n: nk, yTop: py });
      px += s2 * nk * run;
      py -= nk * rise;
      if (left > 0) {                                       // a half turn
        lands.push({ x: px + s2 * w / 2, z: pz + dir * w / 2, y: py,
                     w: w, d: 2 * w, open: [[-s2, 0], [-s2, 0]] });
        px += s2 * w;
        pz += dir * w;
        s2 = -s2;
      }
    }
    out = { flights: flights, lands: lands, footX: px, footZ: pz };
    const yF = surf(px, pz);
    const tot = Math.max(nA + 1, Math.round((yTop - yF) / P.stairRise));
    rise = (yTop - yF) / tot;
    nB = Math.max(1, tot - nA);
    yFoot = yF;
  }
  return { n: nA + nB, rise: rise, w: w, lands: out.lands,
           flights: out.flights, footX: out.footX, footZ: out.footZ,
           footY: yFoot };
}

// one straight flight, along either axis: stringers and treads at lod 0, ONE
// SLOPING CUBOID at lod 1 (a wedge was cheaper still, but a flight reads as a
// raking box at any distance where the far mesh is on screen)
function stepFlight(bags, P, Q, o) {
  const ux = o.ax[0], uz = o.ax[1], px = -uz, pz = ux, hw = o.w / 2;
  const yBot = o.yTop - o.n * o.rise;
  const at = (t, y) => [o.x + ux * t, y, o.z + uz * t];
  const T = o.n * o.run;
  if (Q.lod !== 0) {
    beam(bags.deck, at(0, o.yTop - 0.06), at(T, yBot + 0.05), hw, 0.12,
         [0, 1, 0]);
    return;
  }
  // THE RAMPS. A stringer is a 300 mm board on edge running the whole flight
  // and it is the longest arris on the building; it had none.
  for (const s2 of [-1, 1]) {
    const a = at(0, o.yTop - 0.12), b = at(T, yBot - 0.02);
    beam(bags.post, [a[0] + px * s2 * hw, a[1], a[2] + pz * s2 * hw],
         [b[0] + px * s2 * hw, b[1], b[2] + pz * s2 * hw], 0.03, 0.14,
         [0, 1, 0], 0, bevUV(o.P, Q, jog(a[0] + s2, a[2], 12)));
  }
  // THE HANDRAIL, which is not decoration: a twelve-tread flight two metres
  // up with nothing to hold was in the user's own screenshot, and it is the
  // one part of a porch that is not optional anywhere anybody builds. Posts up
  // the stringer line, a raking cap on top, and — because this is a bench for
  // looking at things — a mid rail when the flight is long enough to want one.
  if (o.rail && o.n >= 3 && T > 0.6) {
    const rh = o.rail;
    const np = Math.max(2, Math.round(T / 1.15));
    for (const s2 of [-1, 1]) {
      const off2 = [px * s2 * hw, pz * s2 * hw];
      for (let i = 0; i <= np; i++) {
        const t2 = T * i / np;
        const y = o.yTop - (t2 / o.run) * o.rise - 0.02;
        const c = at(t2, y);
        beam(bags.post, [c[0] + off2[0], y - 0.10, c[2] + off2[1]],
             [c[0] + off2[0], y + rh, c[2] + off2[1]], 0.032, 0.032,
             [0, 0, 1], 0, bevUV(o.P, Q, jog(c[0], c[2], 11)));
      }
      const a = at(0, o.yTop + rh - 0.02);
      const b = at(T, yBot + rh - 0.02);
      const rb = BEV(o.P, Q);
      beam(bags.deck, [a[0] + off2[0], a[1], a[2] + off2[1]],
           [b[0] + off2[0], b[1], b[2] + off2[1]], 0.036, 0.026, [0, 1, 0],
           0, rb);
      // and the string of bulbs wound on the cap, where the hand goes
      stringLights(bags, o.P, Q, [a[0] + off2[0], a[1] + 0.013, a[2] + off2[1]],
                   [b[0] + off2[0], b[1] + 0.013, b[2] + off2[1]], s2);
      beam(bags.deck, [a[0] + off2[0], a[1] - rh * 0.52, a[2] + off2[1]],
           [b[0] + off2[0], b[1] - rh * 0.52, b[2] + off2[1]], 0.022, 0.018,
           [0, 1, 0], 0, rb);
    }
  }
  for (let i = 0; i < o.n; i++) {                      // a tread on each rise
    const y = o.yTop - (i + 1) * o.rise;
    const c0 = at(i * o.run, y), c1 = at(i * o.run + o.run + 0.03, y);
    boxAB(bags.deck,
          [Math.min(c0[0], c1[0]) - Math.abs(px) * hw, y - 0.045,
           Math.min(c0[2], c1[2]) - Math.abs(pz) * hw],
          [Math.max(c0[0], c1[0]) + Math.abs(px) * hw, y,
           Math.max(c0[2], c1[2]) + Math.abs(pz) * hw], null,
          [(i * 31 % 17) * 0.37, (i * 13 % 11) * 0.29]);
  }
}

// THE PALIER. A rectangle of deck at the height the flight above it ends, on
// four legs cut to the ground under each — the same parts the porch is made
// of, at a quarter of the size, because a landing that is not built like the
// deck is exactly the thing that reads as a floating box. A quarter turn is
// one stair-width square; a half turn is twice as deep, because the two
// flights it joins run side by side.
function buildLanding(bags, P, Q, L, g) {
  const hx = L.w / 2, hz = (L.d || L.w) / 2, rim = L.y - 0.11;
  const x0 = L.x - hx, x1 = L.x + hx, z0 = L.z - hz, z1 = L.z + hz;
  for (const zz of [z0 + 0.07, z1 - 0.07])
    beam(bags.post, [x0, rim, zz], [x1, rim, zz], 0.05, 0.09, [0, 1, 0]);
  if (Q.lod === 0) {
    const bw = P.deckBoard, gp = 0.010;
    const nb = Math.max(1, Math.floor((z1 - z0) / (bw + gp)));
    for (let i = 0; i < nb; i++) {
      const z = z0 + i * (bw + gp);
      boxAB(bags.deck, [x0, L.y - 0.035, z], [x1, L.y, z + bw], null,
            [(i * 37 % 13) * 0.41, (i * 17 % 7) * 0.53]);
    }
  } else boxAB(bags.deck, [x0, L.y - 0.05, z0], [x1, L.y, z1]);
  for (const xx of [x0 + 0.10, x1 - 0.10])
    for (const zz of [z0 + 0.10, z1 - 0.10]) {
      const gy = g(xx, zz);
      if (rim - gy < 0.20) continue;
      beam(bags.post, [xx, gy - 0.05, zz], [xx, rim, zz], P.postSz * 0.42,
           P.postSz * 0.42, [0, 0, 1], 0, { uv: [xx + zz, 0] });
    }
  // A LANDING IS A BALCONY halfway down a stair, so it is railed on every edge
  // a flight does not arrive on — which is what `open` was published for.
  if (Q.lod === 0 && L.rail && L.open) {
    const rh = L.rail;
    const edges = [
      { n: [1, 0], a: [x1, z0], b: [x1, z1] },
      { n: [-1, 0], a: [x0, z0], b: [x0, z1] },
      { n: [0, 1], a: [x0, z1], b: [x1, z1] },
      { n: [0, -1], a: [x0, z0], b: [x1, z0] },
    ];
    for (const e of edges) {
      if (L.open.some(o2 => o2[0] === e.n[0] && o2[1] === e.n[1])) continue;
      const len2 = Math.hypot(e.b[0] - e.a[0], e.b[1] - e.a[1]);
      const np = Math.max(1, Math.round(len2 / 1.0));
      for (let i = 0; i <= np; i++) {
        const u = i / np;
        const x = e.a[0] + (e.b[0] - e.a[0]) * u;
        const z = e.a[1] + (e.b[1] - e.a[1]) * u;
        beam(bags.post, [x, L.y - 0.12, z], [x, L.y + rh, z], 0.032, 0.032,
             [0, 0, 1], 0, bevUV(P, Q, jog(x, z, 13)));
      }
      const lb = BEV(P, Q);
      beam(bags.deck, [e.a[0], L.y + rh, e.a[1]], [e.b[0], L.y + rh, e.b[1]],
           0.036, 0.026, [0, 1, 0], 0, lb);
      stringLights(bags, P, Q, [e.a[0], L.y + rh + 0.013, e.a[1]],
                   [e.b[0], L.y + rh + 0.013, e.b[1]], e.n[0] + e.n[1]);
      beam(bags.deck, [e.a[0], L.y + rh * 0.48, e.a[1]],
           [e.b[0], L.y + rh * 0.48, e.b[1]], 0.022, 0.018, [0, 1, 0], 0, lb);
    }
  }
}

function buildSteps(bags, P, Q, sp, g) {
  for (const f of sp.flights)
    stepFlight(bags, P, Q, { x: f.x, z: f.z, ax: f.ax, n: f.n,
                             run: P.stairRun, rise: sp.rise, yTop: f.yTop,
                             w: sp.w, rail: P.railStyle > 0 ? P.railH : 0,
                             P: P });
  for (const L of sp.lands)
    buildLanding(bags, P, Q,
                 Object.assign({ rail: P.railStyle > 0 ? P.railH : 0 }, L), g);
  return sp.n;
}

// A STOOP: a landing the width of the door, a few steps, and the legs to hold
// it up. It is the deck builder's own parts at a tenth of the size — a door
// onto nothing is not a door anybody uses.
//
// G236: IT SERVES EITHER WALL (the user: "all houses should have stairs and
// entrance. The ones who don't have a door hanging several meters high, not
// very practical"). The back door has had one since G232.3; the FRONT door had
// nothing at all unless the house happened to have a deck, and a house without
// a deck is most of the sheds and half the sampler — so a front door two
// metres up opened onto the drop. `side` is +1 for the front (+z, the deck
// side) and -1 for the back.
function buildStoop(bags, P, Q, V, g, side) {
  const back = (side || -1) < 0;
  if (back && (!P.backDoor || !P.backPorch)) return null;
  if (!back && (!P.door || P.porch)) return null;      // the deck serves it
  if (back && leanCovers(P, V, backDoorX(P, V))) return null;  // inside the shed
  const half = V.wallT / 2;
  const zIn = (back ? -1 : 1) * (V.w / 2 - half);
  const cx = back ? backDoorX(P, V) : (doorPosOf(P, V) - 0.5) * V.L;
  const wid = Math.max(1.0, P.doorW + 0.7), depth = 1.05;
  const zOut = zIn + (back ? -depth : depth);
  const yTop = V.floorY - 0.02;
  const x0 = cx - wid / 2, x1 = cx + wid / 2;
  const rimY = yTop - 0.12;
  beam(bags.post, [x0, rimY, zOut], [x1, rimY, zOut], 0.05, 0.10, [0, 1, 0]);
  for (const x of [x0, x1])
    beam(bags.post, [x, rimY, zIn], [x, rimY, zOut], 0.05, 0.10, [0, 1, 0]);
  const zLo = Math.min(zIn, zOut), zHi = Math.max(zIn, zOut);
  if (Q.lod === 0) {
    const bw = P.deckBoard, gap = 0.008;
    const n = Math.max(1, Math.floor(depth / (bw + gap)));
    for (let i = 0; i < n; i++) {
      const z = zLo + i * (bw + gap);
      const j = (i * 2654435761) >>> 0;
      boxAB(bags.deck, [x0, yTop - 0.035, z], [x1, yTop, z + bw], null,
            [(j % 977) / 977 * 3.1, (j % 383) / 383 * 1.7]);
    }
  } else boxAB(bags.deck, [x0, yTop - 0.05, zLo], [x1, yTop, zHi]);
  for (const x of [x0 + 0.08, x1 - 0.08]) {
    const gy = g(x, zOut);
    if (Math.round(P.stance) === 3)
      cyl(bags.post, [x, gy - 0.3, zOut], [0, 1, 0], P.postSz * 0.55,
          rimY - (gy - 0.3), Q.lod === 0 ? 8 : 4, Q.lod === 0,
          timberUV(x, zOut, 6));
    else
      beam(bags.post, [x, gy, zOut], [x, rimY, zOut], P.postSz * 0.45,
           P.postSz * 0.45, [0, 0, 1]);
  }
  // the steps down to the garden, or onto the landing if this is over water
  const sw = Math.min(wid - 0.2, 1.1);
  const surf = (xx, zz) => {
    const gAt = g(xx, zz);
    return (P.water && gAt < P.waterY) ? P.waterY + 0.38 : gAt;
  };
  // IF IT TURNS, IT TURNS AWAY FROM THE SHED. The lean-to is on this wall and
  // the door has already stepped clear of it; a landing that turned back
  // under it would put the whole point of that back.
  const lsp = back ? leanSpan(P, V) : null;
  const turn = lsp ? (cx >= (lsp[0] + lsp[1]) / 2 ? 1 : -1) : 0;
  const sp = stairPlan(P, { x: cx, w: sw, zTop: zOut, yTop: yTop,
                            dir: back ? -1 : 1, turn: turn }, surf);
  buildSteps(bags, P, Q, sp, g);
  return { x: cx, z: zOut, y: yTop, w: wid, depth: depth, side: back ? -1 : 1,
           steps: sp.n, foot: sp.footZ, turns: sp.lands.length };
}

// ---------------------------------------------------------------------------
// THE LEAN-TO — the second volume, and the proof the layers are layers
// ---------------------------------------------------------------------------
// A shed volume against the back wall, its high plate tucked UNDER the main
// eave so the two roofs never fight. It is built by the same wall() and the
// same plate() as the house; only its roof model differs, and that is one
// plane.
function buildLean(bags, P, Q, V, R, g) {
  const half = V.wallT / 2;
  const zWall = -V.w / 2;                       // it hangs off the back
  const dl = V.L * P.leanLF, cx = P.leanOff * V.L / 2;
  const x0 = cx - dl / 2, x1 = cx + dl / 2;
  const zOut = zWall - P.leanD;
  const k = Math.tan(P.leanPitch * D2R);
  const yHigh = Math.min(V.plateY - 0.15, R.underAt(cx, zWall) - 0.10);
  const yLow = yHigh - k * P.leanD;
  const t = Math.min(V.wallT, 0.14);
  const roofT = Math.min(V.roofT, 0.10);
  const planeC = yHigh + roofT + k * (-zWall);   // y = c + k*z  (rises to +z)
  const under = (x, z) => planeC + k * z - roofT;
  const LR = { underAt: under, planes: [{ a: 0, b: k, c: planeC }],
               topAt: (x, z) => planeC + k * z };
  const plan = [[x0, zWall], [x0, zOut], [x1, zOut], [x1, zWall]];
  // ITS FLOOR (G253): the shed had walls, a roof and legs and nothing to stand
  // on — see-through from below, and a back door that opened into it opened
  // onto air. A slab at the house's own floor line, like the house's.
  boxAB(bags.floor, [x0, V.floorY - 0.10, zOut], [x1, V.floorY - 0.05, zWall]);
  // three walls only: the fourth is the house
  for (let i = 0; i < 3; i++) {
    const A = plan[i], B = plan[i + 1];
    const Lw = Math.hypot(B[0] - A[0], B[1] - A[1]);
    const nO = [-(B[1] - A[1]) / Lw, (B[0] - A[0]) / Lw];
    wall(bags.siding, {
      A: A, B: B, y0: V.floorY - 0.10, t: t,
      ext: [i === 0 ? 0 : t / 2, i === 2 ? 0 : t / 2],
      // inner faces: without them the lean-to is a set of billboards and you
      // see straight through it from the back (the user's screenshots 2 and 3)
      inner: true, sub: Q.lod === 0 ? (P.aoRange || 0.55) * 0.85 : 0,
      topAt: (s, side) => under(
        A[0] + (B[0] - A[0]) * s / Lw + nO[0] * (t / 2) * side,
        A[1] + (B[1] - A[1]) * s / Lw + nO[1] * (t / 2) * side),
      capTop: Q.lod === 0, capBot: false,
      endCap: [false, false],
    });
  }
  const ov = Math.min(0.35, P.eaveOver);
  const ring = [[x0 - ov, LR.topAt(0, zOut - ov), zOut - ov],
                [x1 + ov, LR.topAt(0, zOut - ov), zOut - ov],
                [x1 + ov, LR.topAt(0, zWall + 0.05), zWall + 0.05],
                [x0 - ov, LR.topAt(0, zWall + 0.05), zWall + 0.05]];
  plate(bags.roof, ring, roofT, [0, -1, 0],
        uvFrame(ring[0], [1, 0, 0], nrm(sub(ring[3], ring[0]))),
        { sub: Q.lod === 0 ? 1.1 : 0 });
  // eave and both rakes; the high edge dies into the house wall
  if (Q.lod === 0)
    roofRim(bags.trim, ring, [true, true, false, true],
            roofT + P.fascia * 0.8, 0.030);
  if (Q.lod === 0 && P.ribs && seamsOn(P)) {
    const n = Math.max(1, Math.round((x1 - x0 + 2 * ov) / P.ribPitch));
    for (let i = 0; i <= n; i++) {
      const x = x0 - ov + (x1 - x0 + 2 * ov) * i / n;
      beam(bags.rib, [x, ring[0][1] + P.ribH * 0.5, ring[0][2]],
           [x, ring[3][1] + P.ribH * 0.5, ring[3][2]], 0.016, P.ribH * 0.5,
           [0, 1, 0]);
    }
  }
  // it stands on the same kind of legs
  const nP = Math.max(1, Math.round(dl / P.postSpc));
  for (let i = 0; i <= nP; i++) {
    const x = x0 + dl * i / nP;
    const gy = g(x, zOut);
    beam(bags.post, [x, gy, zOut], [x, V.floorY - 0.12, zOut],
         P.postSz / 2, P.postSz / 2, [0, 0, 1]);
  }
  return { x0, x1, zOut };
}

// ---------------------------------------------------------------------------
// THE CHIMNEY
// ---------------------------------------------------------------------------
function buildChimney(bags, P, Q, V, R) {
  if (!P.chim) return null;
  const x = clamp(P.chimXF * V.L / 2, -V.L / 2 + 0.4, V.L / 2 - 0.4);
  const z = clamp(P.chimZF * V.w / 2, -V.w / 2 + 0.4, V.w / 2 - 0.4);
  const yRoof = R.topAt(x, z);
  const top = yRoof + P.chimUp;
  if (P.chim === 1) {
    const base = V.plateY - 0.5;
    cyl(bags.metal, [x, base, z], [0, 1, 0], P.chimR, top - base,
        Q.lod === 0 ? 12 : 5, true);
    if (Q.lod === 0) {
      // the storm collar where it passes the roof, and a rain cap over it
      cyl(bags.metal, [x, yRoof + 0.02, z], [0, 1, 0], P.chimR * 1.5, 0.09,
          12, true);
      cyl(bags.metal, [x, top + 0.10, z], [0, 1, 0], P.chimR * 1.7, 0.05,
          12, true);
      for (let i = 0; i < 3; i++) {
        const a = 2 * Math.PI * i / 3;
        beam(bags.metal,
             [x + Math.cos(a) * P.chimR, top, z + Math.sin(a) * P.chimR],
             [x + Math.cos(a) * P.chimR, top + 0.10, z + Math.sin(a) * P.chimR],
             0.012, 0.012, [0, 0, 1]);
      }
    }
  } else {
    const r = P.chimR;
    boxAB(bags.stone, [x - r, V.floorY - 0.6, z - r], [x + r, top, z + r]);
    if (Q.lod === 0)
      boxAB(bags.stone, [x - r * 1.2, top, z - r * 1.2],
            [x + r * 1.2, top + 0.10, z + r * 1.2]);
  }
  return { x, z, top, yRoof };
}

// WHAT EACH DOOR OPENS ONTO. `platforms` are rectangles in plan with a top
// height; a door is SERVED when one of them is under the point just outside
// its leaf and within a step of the threshold. The ground counts as a platform
// when the threshold is low enough to walk off, which is what a slab-on-grade
// shed actually has.
function doorReport(P, V, dk, stoop, front, g, openings) {
  const pads = [];
  if (dk && dk.area > 0 && P.porch) {
    const D = deckPlan(P, V);
    pads.push({ x0: D.x0, x1: D.x1, z0: D.zIn, z1: D.zOut, y: V.floorY - 0.02 });
  }
  for (const sp of [stoop, front]) {
    if (!sp) continue;
    const zA = sp.z, zB = sp.z - sp.side * sp.depth;
    pads.push({ x0: sp.x - sp.w / 2, x1: sp.x + sp.w / 2,
                z0: Math.min(zA, zB), z1: Math.max(zA, zB), y: sp.y });
  }
  if (P.lean) {
    const dl = V.L * P.leanLF, cx = P.leanOff * V.L / 2;
    pads.push({ x0: cx - dl / 2, x1: cx + dl / 2, z0: -V.w / 2 - P.leanD,
                z1: -V.w / 2, y: V.floorY - 0.05 });
  }
  const out = [];
  for (const o of openings || []) {
    if (o.kind !== 'door') continue;
    // the point just outside the leaf, in plan
    const s = (o.s0 + o.s1) / 2;
    const half = V.wallT / 2;
    let x, z;
    if (o.side === 0) { x = s - V.L / 2; z = V.w / 2 - half + 0.5; }
    else if (o.side === 2) { x = V.L / 2 - s; z = -(V.w / 2 - half) - 0.5; }
    else continue;                       // no door is put in a gable end
    let best = null;
    for (const q of pads)
      if (x >= q.x0 - 0.15 && x <= q.x1 + 0.15 &&
          z >= q.z0 - 0.15 && z <= q.z1 + 0.15)
        if (best === null || Math.abs(q.y - o.y0) < Math.abs(best - o.y0))
          best = q.y;
    const gy = g(x, z);
    if (best === null && o.y0 - gy < 0.45) best = gy;
    out.push({ x: x, z: z, y0: o.y0, platform: best,
               drop: best === null ? o.y0 - gy : o.y0 - best });
  }
  return out;
}

// ---------------------------------------------------------------------------
// THE PIER (G252, the user: "build more pier structure in front of the houses
// ... When they touch water, they get extended pier modules and small boats")
// ---------------------------------------------------------------------------
// A house that touches the water already has a JETTY: the stair off the deck
// lands on a small platform a hand's breadth over the tide (G232.3), because a
// flight of steps into the sea is the one thing a beach house never has. The
// pier is what that jetty grows into — a run of the kit's modules laid end to
// end at the jetty's own deck height, out into deeper water, ending in the
// kit's head, with boats tied alongside.
//
// It is a PLAN, not geometry: the modules and the boats are baked props (the
// bench and the game instance them through props.js), so what the generator
// owns is where each one goes — key, position, yaw — and it publishes exactly
// that. Headless and deterministic, which is what lets GATE HOUSE hold it: every
// module over water, the run continuous, the head at the end, every boat afloat
// in enough water and clear of the deck and of each other.
//
// Nothing here is a slider on a module: a module is a whole prop, placed by
// its DECK (PIER_KIT.deckY) so the walking surface lands on the jetty's level
// and the piles go wherever the seabed is. That is what "modular" bought.
// THE PATH GRAMMAR (G254, the user: "There are different pieces, for
// straight path, go up one level, with a little doorway ... You may do
// branching, but you may not leave holes in the path"). Read off the kit:
//   RUN    a flat module; the path stays on its level
//   STAIR  one end on the high level and one on the low: the path goes up or
//          down 1.40 m by walking it, and which way is which end you enter
//   GATE   the doorway, 0.46 m deep and no deck of its own - it stands OVER a
//          joint, astride the first half-metre of the next run, exactly as the
//          author stood it astride the 02/03 seam. It advances nothing.
//   HEAD   the landing with the ladder at its far end: where a chain stops
//   SPUR   a branch: a run turned a quarter, its entry end butted to the side
//          of a run on the main chain, at that run's level, ending in a head
// A path is a chain of these where every module ENTERS at the height the one
// before it EXITED and starts where it ended - the same arithmetic as a flight
// of stairs meeting its landing - and the gate holds both, per chain, to the
// centimetre. Everything else is a seed.
function pierPlan(P, V, g, jetty) {
  if (!P.water || !P.pier || !jetty) return null;
  let st = ((P.pierSeed | 0) || 1) * 2654435761 >>> 0;
  const rnd = () => (st = (st * 1664525 + 1013904223) >>> 0) / 4294967296;
  const pick = a => a[Math.min(a.length - 1, Math.floor(rnd() * a.length))];
  const wet = P.waterY;
  const mods = [], boats = [];
  // the frontier of a chain: where it is, how high, which way it runs
  const walk = (chain, x, z, h, ax) => ({ chain, x, z, h, ax });
  // place one module at a chain's frontier and advance it. `ax` is the
  // direction the chain runs in plan (+z out from the jetty for the main
  // chain, +-x for a spur); `flip` enters the module by its z+ end.
  const place = (w, key, flip) => {
    const K = PIER_KIT[key];
    const dIn = flip ? K.deck[1] : K.deck[0], dOut = flip ? K.deck[0] : K.deck[1];
    const y = w.h - dIn;
    // THE PITCH IS THE DECK'S, NOT THE BOX'S: the module's planks start at the
    // frontier and the frontier moves on by the planks' length; whatever the
    // module has past its last plank (a run's bearer and piles, 0.46 m) goes
    // under the next one, which is what it was cut for. Flipped, the deck's
    // extent mirrors.
    const p0 = flip ? -K.dz[1] : K.dz[0], p1 = flip ? -K.dz[0] : K.dz[1];
    const dl = p1 - p0, d = w.ax[0] || w.ax[1];
    const cx = w.x - w.ax[0] * p0, cz = w.z - w.ax[1] * p0;    // box centre
    // yaw: the module's local +z along the chain's axis (+pi if entered flipped)
    let ry = Math.atan2(w.ax[0], w.ax[1]);
    if (flip) ry += Math.PI;
    const a0 = w.ax[0] ? w.x : w.z;
    const m = { key, x: cx, y, z: cz, ry, chain: w.chain,
                axis: w.ax[0] ? 'x' : 'z', dir: d,
                a0: Math.min(a0, a0 + d * dl), a1: Math.max(a0, a0 + d * dl),
                w: K.W, hIn: w.h, hOut: y + dOut,
                z0: cz - (w.ax[1] ? K.L : K.W) / 2, z1: cz + (w.ax[1] ? K.L : K.W) / 2,
                b0: (w.ax[0] ? cx : cz) - K.L / 2, b1: (w.ax[0] ? cx : cz) + K.L / 2 };
    mods.push(m);
    w.x += w.ax[0] * dl; w.z += w.ax[1] * dl; w.h = m.hOut;
    return m;
  };
  const gate = w => {
    const K = PIER_KIT.pier_gate;
    mods.push({ key: 'pier_gate', x: w.x + w.ax[0] * K.L / 2, y: w.h - PIER_DECK,
                z: w.z + w.ax[1] * K.L / 2, ry: Math.atan2(w.ax[0], w.ax[1]),
                chain: w.chain, over: true, w: K.W,
                z0: w.z - K.W / 2, z1: w.z + K.W / 2 });
  };
  const main = walk(0, jetty.x, jetty.z1, jetty.y, [0, 1]);
  const up = clamp(Math.round(P.pierUp), 0, 2);
  // UP ONE LEVEL off the jetty: the stair entered by its low landing
  if (up) place(main, 'pier_step', false);
  if (P.pierGate) gate(main);
  const n = clamp(Math.round(P.pierLen), 1, 6);
  const runs = [];
  for (let i = 0; i < n; i++) runs.push(place(main, pick(PIER_RUNS), false));
  // A BRANCH: a spur off the side of one run, at its level, ending in a head
  let spur = null;
  if (P.pierBranch && n >= 2) {
    const r = runs[Math.floor(rnd() * runs.length)];
    const sd = rnd() < 0.5 ? 1 : -1;
    const w2 = walk(1, r.x + sd * r.w / 2, r.z, r.hOut, [sd, 0]);
    const s1 = place(w2, pick(PIER_RUNS), false);
    s1.off = r; r.spur = sd;
    place(w2, 'pier_head', false);
    spur = w2;
  }
  // AND DOWN AGAIN at the end, to a low landing by the water, or straight to
  // the head on the level the path is on
  if (up === 2) {
    place(main, 'pier_step', true);            // entered by its high end
    place(main, 'pier_run', false);
  }
  const head = place(main, 'pier_head', false);
  const z1 = main.z;
  // a dolphin off the head, one boat's width out on the side the spur is not
  {
    const K = PIER_KIT.pier_piles;
    const sd = spur ? -spur.ax[0] || (rnd() < 0.5 ? 1 : -1) : (rnd() < 0.5 ? 1 : -1);
    const dx = head.x + sd * (head.w / 2 + K.W / 2 + 1.6), dz = z1 - K.L / 2 + 0.6;
    if (g(dx, dz) < wet - 0.8)
      mods.push({ key: 'pier_piles', x: dx, y: head.y, z: dz, ry: 0,
                  z0: dz - K.L / 2, z1: dz + K.L / 2, w: K.W, aside: true });
  }
  // THE BOATS, alongside main-chain modules (not the gate, not under a spur),
  // alternating sides, at the middle of a run, in water deep enough for their
  // own draft, clear of every boat already on that side
  const nb = clamp(Math.round(P.boats), 0, 3);
  const quays = mods.filter(m => m.chain === 0 && !m.over && !m.aside);
  let side = rnd() < 0.5 ? 1 : -1;
  const moor = (key, m, sd) => {
    if (m.spur === sd) return false;
    const K = PIER_KIT[key];
    const bx = m.x + sd * (m.w / 2 + K.W / 2 + 0.35);
    const bz = m.z + (rnd() - 0.5) * Math.max(0, m.z1 - m.z0 - K.L) * 0.5;
    const depth = wet - g(bx, bz);
    if (depth < 0.35 + K.float * K.H) return false;
    // clear of EVERY module - the spur, the dolphin, the doorway's kerb - and
    // not only the one it lies beside: the same box test the gate makes
    for (const q of mods) {
      const hw = (q.axis === 'x' ? (q.b1 - q.b0) : q.w) / 2, hz = (q.z1 - q.z0) / 2;
      if (Math.abs(bx - q.x) < hw + K.W / 2 && Math.abs(bz - q.z) < hz + K.L / 2)
        return false;
    }
    for (const b of boats) {
      const KB = PIER_KIT[b.key];
      if (b.side === sd && Math.abs(b.z - bz) < (K.L + KB.L) / 2 + 0.4)
        return false;
    }
    boats.push({ key, x: bx, y: wet - K.float * K.H, z: bz,
                 ry: (rnd() - 0.5) * 0.16 + (rnd() < 0.5 ? Math.PI : 0),
                 side: sd, run: m.key, depth });
    return true;
  };
  if (P.bigBoat && n >= 3 && moor('boat_grady', head, side)) side = -side;
  for (let k = 0, tries = 0; k < nb && tries < 14; tries++) {
    if (moor(pick(SMALL_BOATS), pick(quays), side)) k++;
    side = -side;
  }
  return { x: jetty.x, y: jetty.y, z0: jetty.z1, z1, up, branch: !!spur,
           modules: mods, boats,
           tris: mods.concat(boats).reduce((a, o) => a + (PIER_TRIS[o.key] || 0), 0) };
}
// THE PILES REACH THE BOTTOM (G254.2, the user: "properly extend the pillars
// of the pier so they reach the bottom ... you may use the texture you use
// for logs and support"). The author cut every pile to the showcase's seabed,
// a metre under the deck; a module placed over three metres of water stood
// on nothing. So every pile the baker found is carried on down, from the foot
// the author left to the seabed it is actually over and a third of a metre
// into it - a plain cylinder in the frame's own material, smooth, the grain
// along it, its own start in the scan, exactly like the house's own piles.
function buildPierPiles(bags, P, Q, plan, g) {
  if (!plan) return 0;
  let n = 0;
  for (const m of plan.modules) {
    const K = PIER_KIT[m.key];
    if (!K || !K.piles) continue;
    const c = Math.cos(m.ry), sn = Math.sin(m.ry);
    for (const pl of K.piles) {
      // the module's frame turned by its yaw (about y: local +z -> world by ry)
      const wx = m.x + pl[0] * c + pl[1] * sn, wz = m.z - pl[0] * sn + pl[1] * c;
      const foot = m.y + pl[3];
      const bed = g(wx, wz);
      if (bed > foot - 0.05) continue;              // the author's cut reaches
      cyl(bags.post, [wx, bed - 0.35, wz], [0, 1, 0], pl[2] * 0.98,
          foot + 0.03 - (bed - 0.35), Q.lod === 0 ? 8 : 4, false,
          timberUV(wx, wz, 21));
      n++;
    }
  }
  return n;
}

