// HOUSE GENERATOR — the wooden-house bench (G229). Alaska: bright painted
// board walls, a ribbed metal roof, and the whole thing standing off wet
// sloping ground on posts.
//
// THE MODEL. Four INDEPENDENT layers, the same discipline as the gear bench,
// so the space stays small and nothing is hard-coded to a "house type":
//
//   1 VOLUME     a rectangular plan L (along the ridge) x w (across it),
//                a floor height, a storey count and a wall thickness. The
//                lean-to is a SECOND volume, not a special case of the first.
//   2 ROOF       a set of PLANES over that plan. gable / shed / saltbox /
//                gambrel differ only in which planes, and the surface is
//                min(planes) everywhere — which is exactly what a roof is.
//                A hip is two more planes, not another roof type.
//   3 STANCE     how it meets the ground: slab, cripple wall, or posts on
//                pads over a SLOPING site. This is the Alaskan layer: the
//                photographs are all of houses standing above the beach.
//   4 FITTINGS   what hangs off it: openings (with trim, reveals, glass),
//                deck and rail and stairs, stove pipe, porch roof.
//
// THE ROOF IS A HEIGHT FIELD, and the walls read it. Every wall is built by
// `_house_kit.js`'s `wall()` with `topAt` = the roof's own underside, so a
// gable end wall is not a triangle somebody drew — it is the eave wall with a
// different top function. Change the pitch and every wall follows it.
//
// TWO MESHES, ONE CONSTRUCTION (the user's ask: high and low poly). `lod` is
// not a decimator and must never become one — the repo's rule is BUILD, DON'T
// RECONSTRUCT. Each builder asks what tier it is drawing for and emits the
// members that survive at that distance: ribs, casings, balusters, joists and
// deck boards simply are not built at lod 1, windows become panes proud of an
// unpierced wall, and the stair becomes the wedge it reads as from 80 m. The
// silhouette is generated by the same numbers, so the two agree by
// construction — GATE HOUSE holds them to it.
