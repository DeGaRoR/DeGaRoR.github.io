// one texture per (set, map): every part that wears a set shares its scale,
// which is the point of a texel-density contract
const TEXC = new Map();
function tex(key, mapName) {
  const S = libSets();
  const set = S && S[key];
  if (!set || !set[mapName]) return null;
  const ck = key + '|' + mapName;
  if (TEXC.has(ck)) return TEXC.get(ck);
  const img = set[mapName];
  const t = new THREE.Texture(img);
  t.wrapS = t.wrapT = THREE.RepeatWrapping;
  t.anisotropy = 8;
  if (mapName === 'diff' || mapName === 'paint') t.encoding = THREE.sRGBEncoding;
  t.repeat.set(1 / set.tile, 1 / set.tile);
  const ok = () => { t.needsUpdate = true; };
  if (img.complete && img.naturalWidth) ok();
  else if (img.addEventListener) img.addEventListener('load', ok);
  TEXC.set(ck, t);
  return t;
}

function dressMat(m, key, colIdx, o) {
  const opt = o || {};
  const S = libSets();
  const set = S && S[key];
  const ci = clamp(Math.round(colIdx || 0), 0, COLS.length - 1);
  // a set that refuses the tint is always worn as delivered, whatever the pot
  // says — see SET_TINT
  const natural = ci === 0 || setTint(key).tint === false;
  if (!set) {                         // no payload: the flat colour stands in
    m.color.setHex(natural ? (opt.flat || 0xb0aaa2) : COLS[ci][1]);
    return;
  }
  const usePaint = !!set.paint && !natural;
  m.map = tex(key, usePaint ? 'paint' : 'diff');
  m.normalMap = tex(key, 'nor');
  m.roughnessMap = tex(key, 'rough');
  // WHERE THE TINT IS APPLIED. `material.color` can only ever multiply, so a
  // blend mode has to be done in the shader — and then the material's own
  // colour must be WHITE or it would multiply first and the blend would work
  // on an already-tinted map.
  const blend = usePaint ? Math.round(opt.blend || 0) : 0;
  const ud = m.userData;
  if (blend > 0 && ud && ud.paint) {
    m.color.setHex(0xffffff);
    ud.paint.uPaintMode.value = blend;
    ud.paint.uPaintCol.value.setHex(blend === 1 ? paintHex(COLS[ci][1])
                                                : COLS[ci][1]);
  } else {
    if (ud && ud.paint) ud.paint.uPaintMode.value = 0;
    m.color.setHex(natural ? 0xffffff
      : (usePaint ? paintHex(COLS[ci][1]) : COLS[ci][1]));
  }
  m.metalness = set.metal;
  m.roughness = opt.rough === undefined ? 1 : opt.rough;
  if (m.normalScale && m.normalScale.set)
    m.normalScale.set(opt.nrm || 1, opt.nrm || 1);
  m.roughness = opt.rough === undefined ? 1 : opt.rough;
  m.needsUpdate = true;
}

// THE ONE PLACE THE HOUSE IS DRESSED. Called before every build, so a set or a
// colour change is a material update and not a rebuild of the geometry.
// ---- what the house wears BEYOND its maps -----------------------------------
// Two things no scanned set can carry, both asked for by the user:
//
//   THE DIRT. "a fading gradient from the bottom simulating ground dust and
//   dirt" — rain throws the beach up the first half metre of any wall in
//   southeast Alaska, and no amount of tiling produces it because it is a
//   function of HEIGHT, not of surface. So it is a shader patch: the world y
//   of every fragment, a smooth ramp above the ground line, mixed toward a
//   dust colour and roughened.
//
//   THE PUNCH. "The coloring of the planks works, but I think it is a little
//   too washed out ... would be good to have a more punchy option". A neutral
//   map times a tint is honest but flat: the map's own greys pull the chroma
//   down. One saturation-and-contrast curve on the diffuse gives back the
//   boat-paint look without touching the library.
//
// ONE patch, applied to every material in the table, so nothing can drift
// between the wall and the trim beside it.
const SHADE_U = {
  uDirtTop: { value: 0.6 }, uDirtH: { value: 0.9 }, uDirtK: { value: 0.45 },
  uDirtCol: { value: null }, uSat: { value: 1.0 }, uCon: { value: 1.0 },
  // how much of the BAKED occlusion is allowed to touch DIRECT light. All of
  // it goes on the indirect term (that is what occlusion means); a third of it
  // on the albedo, which is a cheat and is also the only thing that puts a
  // contact shadow under an eave when the sun is behind you.
  uAOd: { value: 0.35 },
  // THE REPETITION BREAKER (the user: "The plank tiling is very visible on
  // large buildings ... maybe add a layer of procedural noise over the whole
  // building to cut the pure repetition?"). Tiling bigger helps; what kills
  // the copy-paste read is a LOW-FREQUENCY field that does not tile with the
  // texture — a few metres across, in world space, so it drifts over the
  // repeat and no two panels look alike. It rides on albedo and roughness
  // only: no normal, because the surface is not actually bumpy at that scale.
  uNoiseK: { value: 0.16 }, uNoiseS: { value: 3.7 },
};
const DIRT_EXPR =
  'clamp((uDirtTop - vHouseY) / max(0.01, uDirtH), 0.0, 1.0)';

// HOW THE PAINT MEETS THE SCAN (the user: "We should try other blend modes for
// the paint as well, as an option. The wall paint is the one I'm interested
// in"). A multiply is honest and a little dead: the map's own greys pull every
// tint toward grey. The other four are the ones a painter would recognise —
// overlay and soft light keep the boards' light and shade while the colour
// takes over, tint throws the scan's colour away entirely and keeps only its
// VALUE (the cleanest, newest-looking paint), and screen is limewash.
const PAINT_BLENDS = ['multiply', 'overlay', 'soft light', 'tint', 'limewash'];

function shadeHouse(m) {
  const ud = m.userData || (m.userData = {});   // a stub may not have one
  if (ud.houseShaded) return;
  ud.houseShaded = true;
  // per-material, because only the wall is painted this way
  ud.paint = { uPaintCol: { value: new THREE.Color(1, 1, 1) },
               uPaintMode: { value: 0 } };
  // THE DIRT IS PER MATERIAL, not one ramp for the whole house (the user:
  // "All foundations need to be subject to the dirt gradient"). Height is
  // shared — the splash line is the splash line — but what the splash DOES is
  // not: on painted cladding it is pale dust off a dry track, and on the
  // concrete it stands on it is the dark tide line of something that has been
  // wet a hundred times. One colour for both made the foundation look
  // bleached, which is how it came to look like it was not in the ramp at all.
  ud.dirt = { uDirtOwn: { value: new THREE.Color(0x6d6353) },
              uDirtGain: { value: 1.0 },
              // G236: and how OLD this material is on its own account —
              // chroma out, value down. The frame under a house is never
              // newer than the wall above it.
              uAgeDesat: { value: 0.0 }, uAgeDark: { value: 0.0 } };
  if (!SHADE_U.uDirtCol.value) SHADE_U.uDirtCol.value = new THREE.Color(0x6d6353);
  m.onBeforeCompile = sh => {
    for (const k in SHADE_U) sh.uniforms[k] = SHADE_U[k];
    for (const k in ud.paint) sh.uniforms[k] = ud.paint[k];
    for (const k in ud.dirt) sh.uniforms[k] = ud.dirt[k];
    sh.vertexShader = 'varying float vHouseY;\nvarying float vHouseAO;\n' +
      'varying vec3 vHouseP;\nattribute float aHouseAO;\n' +
      sh.vertexShader.replace(
      '#include <begin_vertex>',
      '#include <begin_vertex>\n  vHouseP = (modelMatrix * vec4(transformed, 1.0)).xyz;' +
      '\n  vHouseY = vHouseP.y;\n  vHouseAO = aHouseAO;');
    sh.fragmentShader =
      'varying float vHouseY;\nvarying float vHouseAO;\nvarying vec3 vHouseP;\n' +
      'uniform float uDirtTop, uDirtH, uDirtK, uSat, uCon, uAOd, uNoiseK, uNoiseS;\n' +
      'uniform vec3 uDirtCol, uDirtOwn, uPaintCol;\n' +
      'uniform float uPaintMode, uDirtGain, uAgeDesat, uAgeDark;\n' +
      'float hHash(vec3 p) { return fract(sin(dot(floor(p), ' +
      'vec3(127.1, 311.7, 74.7))) * 43758.5453); }\n' +
      'float hNoise(vec3 p) {\n' +
      '  vec3 i = floor(p), f = fract(p);\n' +
      '  f = f * f * (3.0 - 2.0 * f);\n' +
      '  float n = mix(mix(mix(hHash(i), hHash(i + vec3(1,0,0)), f.x),\n' +
      '                    mix(hHash(i + vec3(0,1,0)), hHash(i + vec3(1,1,0)), f.x), f.y),\n' +
      '                mix(mix(hHash(i + vec3(0,0,1)), hHash(i + vec3(1,0,1)), f.x),\n' +
      '                    mix(hHash(i + vec3(0,1,1)), hHash(i + vec3(1,1,1)), f.x), f.y), f.z);\n' +
      '  return n;\n}\n' + sh.fragmentShader
      .replace('#include <map_fragment>', '#include <map_fragment>\n' +
        '  {\n' +
        '    if (uPaintMode > 0.5) {\n' +
        '      vec3 mp = diffuseColor.rgb, pc = uPaintCol;\n' +
        '      vec3 ov = mix(2.0 * mp * pc, 1.0 - 2.0 * (1.0 - mp) * (1.0 - pc),\n' +
        '                    step(0.5, mp));\n' +
        '      vec3 sl = (1.0 - 2.0 * pc) * mp * mp + 2.0 * pc * mp;\n' +
        '      float lu = dot(mp, vec3(0.2126, 0.7152, 0.0722));\n' +
        '      vec3 tn = pc * (0.55 + lu * 0.75);\n' +
        '      vec3 sc = 1.0 - (1.0 - mp) * (1.0 - pc);\n' +
        '      if (uPaintMode < 1.5) diffuseColor.rgb = mp * pc;\n' +
        '      else if (uPaintMode < 2.5) diffuseColor.rgb = ov;\n' +
        '      else if (uPaintMode < 3.5) diffuseColor.rgb = sl;\n' +
        '      else if (uPaintMode < 4.5) diffuseColor.rgb = tn;\n' +
        '      else diffuseColor.rgb = sc;\n' +
        '    }\n' +
        '    vec3 hc = diffuseColor.rgb;\n' +
        '    float hl = dot(hc, vec3(0.2126, 0.7152, 0.0722));\n' +
        // THE PUNCH ROLLS OFF ON A COLOUR THAT ALREADY HAS ONE (the user:
        // "you should limit the paint punch generally speaking, it
        // oversaturates and over contrasts, to unnatural looks, especially on
        // long boards"). A flat gain is the wrong instrument: it was written
        // to rescue the CHROMA the neutral map takes out of a tint, and on a
        // washed-out grey plank that is exactly right — but applied to paint
        // that is already at 0.4 chroma it walks straight off the end of the
        // gamut, and on a long board there is no joint to break up the
        // result. So the lift is scaled by the room the pixel still has:
        // full on a grey, nothing on a saturated red. The contrast keeps a
        // third of its gain everywhere, because some of it is doing honest
        // work on the scan's own shading.
        '    float hch = max(max(hc.r, hc.g), hc.b) - min(min(hc.r, hc.g), hc.b);\n' +
        '    float hroom = 1.0 - clamp(hch * 2.6, 0.0, 1.0);\n' +
        '    hc = mix(vec3(hl), hc, 1.0 + (uSat - 1.0) * hroom);\n' +
        '    hc = clamp((hc - 0.5) * (1.0 + (uCon - 1.0) * (0.35 + 0.65 * hroom))\n' +
        '               + 0.5, 0.0, 1.0);\n' +
        '    hc = mix(hc, vec3(dot(hc, vec3(0.2126, 0.7152, 0.0722))),\n' +
        '             uAgeDesat) * (1.0 - uAgeDark);\n' +
        '    float hd = clamp(pow(' + DIRT_EXPR + ', 1.7) * uDirtK * uDirtGain,\n' +
        '                     0.0, 0.95);\n' +
        '    diffuseColor.rgb = mix(hc, uDirtOwn, hd);\n' +
        '    diffuseColor.rgb *= mix(1.0, clamp(vHouseAO, 0.0, 1.0), uAOd);\n' +
        '    float hn = hNoise(vHouseP / uNoiseS) * 0.65 +\n' +
        '               hNoise(vHouseP / (uNoiseS * 0.37)) * 0.35;\n' +
        '    diffuseColor.rgb *= 1.0 + (hn - 0.5) * 2.0 * uNoiseK;\n' +
        '  }')
      // and the whole of it on the indirect term, which is where three itself
      // applies an aoMap — this is that, sourced from a vertex attribute
      .replace('#include <aomap_fragment>', '#include <aomap_fragment>\n' +
        '  reflectedLight.indirectDiffuse *= clamp(vHouseAO, 0.0, 1.0);')
      .replace('#include <roughnessmap_fragment>',
        '#include <roughnessmap_fragment>\n' +
        '  roughnessFactor = clamp(roughnessFactor + (hNoise(vHouseP / ' +
        '(uNoiseS * 0.61)) - 0.5) * uNoiseK * 1.2 + pow(' + DIRT_EXPR +
        ', 1.7) * uDirtK * uDirtGain * 0.5, 0.04, 1.0);');
  };
  m.needsUpdate = true;
}

// HOW HARD EACH SURFACE'S NORMAL MAP IS PUSHED. Sawn timber at a metre and a
// bit per tile has real relief and a normalScale of 1 was reading flat — a
// plank wall wants to catch a raking sun. Metal sheet is the opposite: it is
// smooth between its ribs, and the ribs are in the geometry or in the map's
// own profile, so it stays near 1.
const NRM = { siding: 1.7, trim: 1.3, deck: 1.6, post: 1.5, floor: 1.6,
              stone: 1.4, roof: 1.1, rib: 1.0, metal: 1.0 };

// THE GLASS PATCH (the user: "enhance the window material. We don't need
// transparency, but it has to take the light better. Glares, reflections,
// possibly imperfections").
//
// WHAT WAS WRONG, and it was arithmetic rather than taste: the roughness noise
// was ADDED (`rough + field * dial`), so the dial the user had set to 0.4 was
// not adding variation, it was adding 0.2 of average blur on top of a 0.12
// base and clamping near the 0.5 ceiling. A window at roughness 0.4 has no
// glare, no sky in it and no edge — it is grey paint that happens to be dark.
// The noise is CENTRED now: the mean stays where the material put it and the
// dial buys imperfection, which is what it was asked for.
//
// Then three things that make an opaque pane read as glass:
//   FRESNEL. Glass reflects a few percent head-on and nearly everything at a
//   grazing angle, and that ramp is most of what the eye reads. Both specular
//   terms are lifted by (1-cos)^5, so a wall of windows goes bright at the
//   edge of the building and stays dark facing you.
//   METALNESS. In a metal/rough workflow the cheapest honest dark mirror is a
//   dark base colour at part metalness: the environment comes back tinted by
//   the glass instead of washed white, and the sun is a hard little glint
//   rather than a grey smear.
//   SMEARS. A vertical, stretched noise on roughness — rain tracks. It is the
//   only thing on a flat pane that gives the reflection something to break
//   over, and it costs one more sample of the field already being computed.
function shadeGlass(m) {
  const ud = m.userData || (m.userData = {});
  if (ud.glassShaded) return;
  ud.glassShaded = true;
  m.onBeforeCompile = sh => {
    sh.uniforms.uGlassWave = GLASS_U.uGlassWave;
    sh.uniforms.uGlassRough = GLASS_U.uGlassRough;
    sh.uniforms.uGlassFres = GLASS_U.uGlassFres;
    sh.uniforms.uLitK = GLASS_U.uLitK;
    sh.vertexShader = 'varying vec3 vGlassP;\nvarying float vHouseLit;\n' +
      'attribute float aHouseLit;\n' + sh.vertexShader.replace(
      '#include <begin_vertex>',
      '#include <begin_vertex>\n  vGlassP = (modelMatrix * vec4(transformed, 1.0)).xyz;' +
      '\n  vHouseLit = aHouseLit;');
    sh.fragmentShader =
      'varying vec3 vGlassP;\nvarying float vHouseLit;\n' +
      'uniform float uGlassWave, uGlassRough, uGlassFres, uLitK;\n' +
      // THE PALETTE OF WHAT GLOWS: the warm of a room with a lamp on, and the
      // four colours of a string of Christmas bulbs
      'vec3 gLitCol(float k) {\n' +
      '  if (k < 1.5) return vec3(1.00, 0.72, 0.40);\n' +
      '  if (k < 2.5) return vec3(1.00, 0.10, 0.06);\n' +
      '  if (k < 3.5) return vec3(0.12, 1.00, 0.22);\n' +
      '  if (k < 4.5) return vec3(0.22, 0.42, 1.00);\n' +
      '  return vec3(1.00, 0.70, 0.16);\n}\n' +
      'float gHash(vec3 p) { return fract(sin(dot(floor(p), ' +
      'vec3(127.1, 311.7, 74.7))) * 43758.5453); }\n' +
      'float gNoise(vec3 p) {\n' +
      '  vec3 i = floor(p), f = fract(p);\n' +
      '  f = f * f * (3.0 - 2.0 * f);\n' +
      '  return mix(mix(mix(gHash(i), gHash(i + vec3(1,0,0)), f.x),\n' +
      '                 mix(gHash(i + vec3(0,1,0)), gHash(i + vec3(1,1,0)), f.x), f.y),\n' +
      '             mix(mix(gHash(i + vec3(0,0,1)), gHash(i + vec3(1,0,1)), f.x),\n' +
      '                 mix(gHash(i + vec3(0,1,1)), gHash(i + vec3(1,1,1)), f.x), f.y), f.z);\n}\n' +
      'float gField(vec3 p) { return gNoise(p) * 0.6 + gNoise(p * 2.3) * 0.3 +\n' +
      '                              gNoise(p * 5.1) * 0.1; }\n' +
      sh.fragmentShader
        .replace('#include <roughnessmap_fragment>',
          '#include <roughnessmap_fragment>\n' +
          '  {\n' +
          '    float gs = gField(vec3(vGlassP.x * 2.6, vGlassP.y * 0.35,\n' +
          '                           vGlassP.z * 2.6));\n' +
          '    float gv = (gField(vGlassP * 0.9) - 0.5) * 0.75 + (gs - 0.5);\n' +
          '    roughnessFactor = clamp(roughnessFactor + gv * uGlassRough,\n' +
          '                            0.015, 0.45);\n' +
          '  }')
        .replace('#include <lights_fragment_end>',
          '#include <lights_fragment_end>\n' +
          '  {\n' +
          '    float gf = pow(clamp(1.0 - abs(dot(geometry.normal,\n' +
          '                     geometry.viewDir)), 0.0, 1.0), 5.0);\n' +
          '    float gk = 1.0 + uGlassFres * gf;\n' +
          // a lit pane is a light, not a mirror: the room behind it drowns
          // most of what the glass was reflecting
          '    float glit = step(0.5, vHouseLit);\n' +
          '    gk *= 1.0 - 0.6 * glit;\n' +
          '    reflectedLight.directSpecular *= gk;\n' +
          '    reflectedLight.indirectSpecular *= gk;\n' +
          '  }')
        .replace('#include <emissivemap_fragment>',
          '#include <emissivemap_fragment>\n' +
          '  if (vHouseLit > 0.5) {\n' +
          // the slow field puts a little unevenness across a lit pane — a
          // curtain, a lamp nearer one side — so twelve windows are not
          // twelve identical rectangles
          '    float gu = 0.80 + 0.35 * gField(vGlassP * 0.7);\n' +
          '    totalEmissiveRadiance += gLitCol(vHouseLit) * uLitK * gu;\n' +
          '  }')
        .replace('#include <normal_fragment_maps>',
          '#include <normal_fragment_maps>\n' +
          '  {\n' +
          '    float e = 0.11;\n' +
          '    float n0 = gField(vGlassP * 1.7);\n' +
          '    float nx = gField((vGlassP + vec3(e, 0.0, 0.0)) * 1.7) - n0;\n' +
          '    float ny = gField((vGlassP + vec3(0.0, e, 0.0)) * 1.7) - n0;\n' +
          '    normal = normalize(normal + vec3(nx, ny, 0.0) * uGlassWave);\n' +
          '  }');
  };
  m.needsUpdate = true;
}
// THE GLASS THE USER ASKED FOR: "the windows should not really be see
// through. A reflective surface, with a tiny bit of musgrave (field) as normal
// and a little perlin noise as roughness ... You can lower the glass waviness
// to 0,2 and the roughness to 0,4". 1.6 was a bottle bottom — it tilted the
// normal far enough to break the reflection into facets, which reads as
// hammered glass, not as glass. At 0.2 the field only bends what is already
// reflected; the roughness at 0.4 is what stops the pane being a mirror.
const GLASS_U = { uGlassWave: { value: 0.2 }, uGlassRough: { value: 0.4 },
                  uGlassFres: { value: 2.6 }, uLitK: { value: 2.2 } };

// ---------------------------------------------------------------------------
// THE GROUND UNDER THE BUILDING (the user: "You should add some terrain
// ambient occlusion too, as maybe a simple gradient from the terrain onwerds")
// ---------------------------------------------------------------------------
// The house bakes its own occlusion per vertex, but the TERRAIN is not the
// house's mesh — it belongs to the site in the bench and to the world in the
// game — so the one thing that ties a building to the ground it stands on was
// missing: the ground stayed the same grass right up to the wall, and every
// house read as a sticker.
//
// It does not need a bake. What is under a building is a rectangle, and the
// darkening is a function of the DISTANCE TO THAT RECTANGLE: full underneath
// (a crawl space is dark), falling off over a couple of metres outside it.
// Signed box distance in the fragment shader, two uniforms and a radius —
// which means it costs nothing, follows the building when a slider moves, and
// ports to the game as one call on whatever material the terrain wears.
const GROUND_U = {
  uGCtr: { value: null }, uGHalf: { value: null },
  uGR: { value: 2.6 }, uGK: { value: 0.55 },
};
function shadeGround(m, foot, o) {
  if (!m) return;
  const opt = o || {};
  if (!GROUND_U.uGCtr.value) {
    GROUND_U.uGCtr.value = new THREE.Vector2(0, 0);
    GROUND_U.uGHalf.value = new THREE.Vector2(1, 1);
  }
  if (foot) {
    GROUND_U.uGCtr.value.set(foot.cx, foot.cz);
    GROUND_U.uGHalf.value.set(foot.hx, foot.hz);
  }
  GROUND_U.uGR.value = opt.reach === undefined ? 2.6 : opt.reach;
  GROUND_U.uGK.value = opt.strength === undefined ? 0.55 : opt.strength;
  const ud = m.userData || (m.userData = {});
  if (ud.groundShaded) return;
  ud.groundShaded = true;
  m.onBeforeCompile = sh => {
    for (const k in GROUND_U) sh.uniforms[k] = GROUND_U[k];
    sh.vertexShader = 'varying vec3 vGrP;\n' + sh.vertexShader.replace(
      '#include <begin_vertex>',
      '#include <begin_vertex>\n  vGrP = (modelMatrix * vec4(transformed, 1.0)).xyz;');
    sh.fragmentShader =
      'varying vec3 vGrP;\nuniform vec2 uGCtr, uGHalf;\n' +
      'uniform float uGR, uGK;\n' + sh.fragmentShader.replace(
      '#include <map_fragment>', '#include <map_fragment>\n' +
      '  {\n' +
      '    vec2 gd = abs(vGrP.xz - uGCtr) - uGHalf;\n' +
      '    float gdist = length(max(gd, vec2(0.0))) +\n' +
      '                  min(max(gd.x, gd.y), 0.0);\n' +
      '    float gk = clamp(1.0 - max(gdist, 0.0) / max(uGR, 0.01), 0.0, 1.0);\n' +
      '    gk = gk * gk * (3.0 - 2.0 * gk);\n' +
      '    if (gdist < 0.0) gk = 1.0;\n' +
      '    diffuseColor.rgb *= 1.0 - uGK * gk;\n' +
      '  }');
  };
  m.needsUpdate = true;
}

// ---------------------------------------------------------------------------
// CHEAP CHIMNEY SMOKE (G254). Nine puffs of two crossed quads each, rising
// from the chimney's own top, widening and thinning as they go and leaning a
// little downwind. What makes it read is all in the fragment: a soft disc in
// each quad (its uvs are metres from the puff's centre, so the disc is a
// radius), a value noise that the bench scrolls UPWARD with time so the column
// seems to rise without a vertex ever moving, and a fade with age so the top
// dissolves. Thirty-six triangles for the near mesh, sixteen for the far one,
// and no light touches it.
const SMOKE_U = { uTime: { value: 0 }, uSmokeK: { value: 0.55 } };
const SMOKE_R0 = 0.18, SMOKE_R1 = 1.15;   // a puff's radius: R0 + age * R1
function shadeSmoke(m) {
  const ud = m.userData || (m.userData = {});
  if (ud.smokeShaded) return;
  ud.smokeShaded = true;
  m.onBeforeCompile = sh => {
    sh.uniforms.uTime = SMOKE_U.uTime;
    sh.uniforms.uSmokeK = SMOKE_U.uSmokeK;
    sh.vertexShader = 'attribute float aHouseLit;\nvarying float vAge;\n' +
      'varying vec2 vSm;\n' + sh.vertexShader
      .replace('#include <begin_vertex>',
               '#include <begin_vertex>\n  vAge = aHouseLit;\n  vSm = uv;');
    sh.fragmentShader = 'varying float vAge;\nvarying vec2 vSm;\n' +
      'uniform float uTime, uSmokeK;\n' +
      'float sHash(vec2 p) { return fract(sin(dot(p, vec2(127.1, 311.7))) * 43758.5453); }\n' +
      'float sNoise(vec2 p) {\n' +
      '  vec2 i = floor(p), f = fract(p);\n' +
      '  f = f * f * (3.0 - 2.0 * f);\n' +
      '  return mix(mix(sHash(i), sHash(i + vec2(1, 0)), f.x),\n' +
      '             mix(sHash(i + vec2(0, 1)), sHash(i + vec2(1, 1)), f.x), f.y);\n}\n' +
      sh.fragmentShader.replace('#include <color_fragment>',
        '#include <color_fragment>\n' +
        '  {\n' +
        '    float r = ' + SMOKE_R0.toFixed(3) + ' + vAge * ' + SMOKE_R1.toFixed(3) + ';\n' +
        '    float d = length(vSm) / r;\n' +
        '    vec2 q = vSm / r * 2.2 + vec2(0.0, -uTime * 0.35) + vAge * 3.1;\n' +
        '    float n = sNoise(q) * 0.6 + sNoise(q * 2.3 + 7.0) * 0.4;\n' +
        '    float a = smoothstep(1.0, 0.25, d) * (0.35 + 0.65 * n) *\n' +
        '              pow(1.0 - vAge, 1.4) * uSmokeK;\n' +
        '    a *= smoothstep(0.0, 0.08, vAge + 0.02);\n' +
        '    diffuseColor.a *= a;\n' +
        '    diffuseColor.rgb *= 0.85 + 0.25 * n;\n' +
        '  }');
  };
  m.needsUpdate = true;
}

function buildSmoke(bags, P, Q, ch) {
  if (!P.smoke || !ch) return null;
  const n = Q.lod === 0 ? 9 : 4;
  const rise = 3.2, lean = clamp(P.smokeLean === undefined ? 0.35 : P.smokeLean, -1, 1);
  const bag = bags.smoke;
  for (let i = 0; i < n; i++) {
    const age = n > 1 ? i / (n - 1) : 0;
    const r = SMOKE_R0 + age * SMOKE_R1;
    const c = [ch.x + lean * age * age * 1.6, ch.top + 0.15 + age * rise,
               ch.z + lean * age * age * 0.5];
    bag.setGlow(age);
    for (const ax of [[1, 0, 0], [0, 0, 1]]) {
      const up = [0, 1, 0];
      const q = [add(add(c, mul(ax, -r)), mul(up, -r)), add(add(c, mul(ax, r)), mul(up, -r)),
                 add(add(c, mul(ax, r)), mul(up, r)), add(add(c, mul(ax, -r)), mul(up, r))];
      face(bag, q, crs(ax, up), uvFrame(c, ax, up));
    }
    bag.setGlow(0);
  }
  return { x: ch.x, z: ch.z, y0: ch.top, y1: ch.top + 0.15 + rise, puffs: n };
}

function applyFinish(P) {
  shadeSmoke(MAT.smoke);
  SMOKE_U.uSmokeK.value = P.smokeK === undefined ? 0.55 : P.smokeK;
  for (const k of BAGS) if (k !== 'glass' && k !== 'pane' && MAT[k])
    shadeHouse(MAT[k]);
  shadeGlass(MAT.glass); shadeGlass(MAT.pane);
  GLASS_U.uGlassWave.value = P.glassWave === undefined ? 0.2 : P.glassWave;
  GLASS_U.uGlassRough.value = P.glassRough === undefined ? 0.4 : P.glassRough;
  GLASS_U.uGlassFres.value = P.glassFres === undefined ? 2.6 : P.glassFres;
  GLASS_U.uLitK.value = P.lightK === undefined ? 2.2 : P.lightK;
  // the ground line under the middle of the building, and how far the dust
  // climbs; the punch is one dial from washed-out to boat paint
  const g = groundFn(P);
  SHADE_U.uDirtTop.value = g(0, 0) + (P.dirtH || 0) * 0.55;
  SHADE_U.uDirtH.value = Math.max(0.05, P.dirtH || 0.9);

  SHADE_U.uAOd.value = P.aoDirect === undefined ? 0.35 : P.aoDirect;
  // WHAT EACH MATERIAL DOES WITH THE SPLASH. Everything wooden takes the pale
  // dust; the concrete takes a darker, WETTER line and takes more of it,
  // because that is what a foundation looks like after one winter and it is
  // the reason the user could not see the ramp on it at all.
  const age = clamp(P.frameAge === undefined ? 0.55 : P.frameAge, 0, 1);
  for (const k of BAGS) {
    const ud = MAT[k] && MAT[k].userData && MAT[k].userData.dirt;
    if (!ud) continue;
    const stone = k === 'stone';
    ud.uDirtGain.value = stone ? 1.55 : (k === 'post' ? 1.35 : 1.0);
    ud.uDirtOwn.value.setHex(stone ? 0x453f36 : 0x6d6353);
    // THE FRAME IS ALWAYS OLDER THAN THE HOUSE. Nobody paints a bearer, and
    // nothing under a building stays the colour it was cut. `post` is the
    // whole structural frame now — piles, posts, braces, bearers, joists,
    // stringers — so one dial ages all of it together, and it is applied on
    // TOP of whatever weathering the rest of the house has, never below it.
    ud.uAgeDesat.value = k === 'post' ? age * 0.85 : 0;
    ud.uAgeDark.value = k === 'post' ? age * 0.52 : 0;
  }
  // WEATHER IS THE OTHER HALF OF THE PAINT DIAL (the user: "that looked newer,
  // less weathered ... would be nice to have more weathered and more fresh
  // looks blended in the different generated houses"). Fresh paint is
  // saturated and even; twenty winters take the chroma out of it, flatten the
  // contrast and put the beach up the first half metre. One number moves all
  // three, so a village can be a mix rather than a set.
  SHADE_U.uNoiseK.value = P.noise === undefined ? 0.16 : P.noise;
  SHADE_U.uNoiseS.value = P.noiseS || 3.7;
  const wthr = clamp(P.weather === undefined ? 0.5 : P.weather, 0, 1);
  // THE CAP IS THE LIBRARY'S, NOT THE SLIDER'S. A set that says it cannot
  // carry the punch (SET_TINT) caps it for the whole house, because the
  // saturation and contrast lift is ONE pair of uniforms shared by every
  // material — there is no way to punch the trim and spare the wall it is
  // nailed to. The cap is taken over the roles that cover real area.
  let punch = P.paintPunch === undefined ? 0.25 : P.paintPunch;
  for (const role of ['wall', 'trim', 'deck', 'post', 'floor']) {
    const cap = setTint(setFor(P, role)).punch;
    if (cap !== undefined) punch = Math.min(punch, cap);
  }
  // and the gains themselves are halved from the first cut: 0.65 on the
  // saturation was enough to take a mid red past the sRGB gamut before the
  // rolloff was in the shader, and the two together were doing the same work
  // twice
  SHADE_U.uSat.value = Math.max(0.35, 1 + punch * 0.35 - wthr * 0.45);
  SHADE_U.uCon.value = Math.max(0.80, 1 + punch * 0.16 - wthr * 0.14);
  SHADE_U.uDirtK.value = (P.dirt === undefined ? 0.45 : P.dirt) *
                         (0.35 + wthr * 1.1);
  dressMat(MAT.siding, setFor(P, 'wall'), P.wallCol,
          { flat: 0xa8302a, nrm: NRM.siding, blend: P.paintBlend });
  dressMat(MAT.trim, setFor(P, 'trim'), P.trimCol,
          { flat: 0xe8e6df, nrm: NRM.trim });
  dressMat(MAT.roof, setFor(P, 'roof'), P.roofCol,
          { flat: 0x9aa3aa, nrm: NRM.roof });
  dressMat(MAT.rib, setFor(P, 'roof'), P.roofCol,
          { flat: 0x8d969d, nrm: NRM.rib });
  // BOARDS take a veneer, SURFACES take planks: the deck's members and the
  // rail are individual sticks; the floor slab and the far mesh's deck are
  // continuous surfaces
  dressMat(MAT.deck, setFor(P, 'deck'), P.deckCol,
          { flat: 0x9c8a6f, nrm: NRM.deck });
  dressMat(MAT.floor, setFor(P, 'floor'), 0,
          { flat: 0x6d6154, nrm: NRM.floor });
  dressMat(MAT.post, setFor(P, 'post'), P.postCol,
          { flat: 0x4a4038, nrm: NRM.post });
  dressMat(MAT.stone, setFor(P, 'stone'), 0,
          { flat: 0x8e8b85, nrm: NRM.stone });
  dressMat(MAT.metal, setFor(P, 'metal'), P.metalCol,
          { flat: 0xb4bcc2, nrm: NRM.metal, rough: 0.85 });
  MAT.pane.map = null; MAT.pane.normalMap = null; MAT.pane.roughnessMap = null;
  // the far mesh's pane is the same glass one step duller: it is seen from far
  // enough that a hard glint would twinkle as the camera moves
  MAT.pane.color.setHex(0x141c22);
  MAT.pane.roughness = 0.10; MAT.pane.metalness = 0.45;
  MAT.pane.needsUpdate = true;
  MAT.glass.color.setHex(0x101a20);
  MAT.glass.roughness = 0.06; MAT.glass.metalness = 0.62;
  if (MAT.glass.envMapIntensity !== undefined) {
    MAT.glass.envMapIntensity = 2.3; MAT.pane.envMapIntensity = 1.9;
  }
}

