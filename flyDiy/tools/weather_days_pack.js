#!/usr/bin/env node
// ============================================================
// THE WEATHER DAYS' PACK (WEATHER-SEASON, 2026-11-03): src/weather/days/<block>/*.json -> src/core/07c_weather_days.js
// The 42 crafted days the user approved (3 Nov, "seasons look OK"; futureDesigns/WEATHER-DAYS-STUDY-2026-11.md §4, §10)
// are authored as one JSON a day; the core carries them as ONE constant (the page and the physics worker read the same
// bytes). The output is GENERATED - edit a day's JSON and run this; GATE WEATHERPLAN holds the two equal.
//   node tools/weather_days_pack.js            write the pack
//   node tools/weather_days_pack.js --check    exit 1 if the pack is not what the JSONs make
// ============================================================
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const DIR = path.join(ROOT, 'src', 'weather', 'days'), OUT = path.join(ROOT, 'src', 'core', '07c_weather_days.js');
const BLOCKS = ['early', 'high', 'late'];
function pack() {
  const days = {};
  for (const b of BLOCKS) days[b] = fs.readdirSync(path.join(DIR, b)).filter(f => /\.json$/.test(f)).sort()
    .map(f => JSON.parse(fs.readFileSync(path.join(DIR, b, f), 'utf8')));
  return '// ============================================================\n'
    + '// GENERATED by tools/weather_days_pack.js from src/weather/days/<block>/*.json - never hand-edit (GATE WEATHERPLAN).\n'
    + '// The crafted weather days: three seasonal blocks of 14 (early 20 May-2 Jul, high 3 Jul-15 Aug, late 16 Aug-30 Sep),\n'
    + '// read by 07d_weather_plan.js. futureDesigns/WEATHER-DAYS-STUDY-2026-11.md §4, §10, Appendix B (the schema).\n'
    + '// ============================================================\n'
    + 'const WEATHER_DAYS = Object.freeze({\n'
    + BLOCKS.map(b => '  ' + b + ': [\n' + days[b].map(d => '    ' + JSON.stringify(d)).join(',\n') + '\n  ]').join(',\n')
    + '\n});\n';
}
const text = pack();
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== text) { console.log('weather_days_pack: src/core/07c_weather_days.js is STALE - run node tools/weather_days_pack.js'); process.exit(1); }
  console.log('weather_days_pack: the pack is the JSONs'); process.exit(0);
}
fs.writeFileSync(OUT, text);
console.log('weather_days_pack: wrote ' + path.relative(ROOT, OUT) + ' (' + text.length + ' bytes)');
